# Builds config/gui-font.json (Q272): an original 8-row pixel font for the MCP GUI preview. Rows 0-6 sit above the
# baseline, row 7 below; '#' is ink. Glyph widths follow Minecraft's font closely (most 5, i/!/. 1, l 2, I/t 3), so text
# measured with it matches the game's text width.
#   py -3 tools/gui-font.py
