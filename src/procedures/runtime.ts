/** <Mod>Procedures: network, queue ticking, variable lifecycle and the global trigger listeners. */
export function registrationSource(env: ProcEnv, triggerCode: string[], usesQueue: boolean, hasPlayerVars: boolean, syncsVars: boolean): JavaSource {
  const pkg = `${env.pkg}.procedures`;
  const cls = `${env.modClass}Procedures`;
  const bus = env.loader === "fabric" ? "" : env.loader === "neoforge" ? "net.neoforged.bus.api.IEventBus modBus" : "net.minecraftforge.eventbus.api.IEventBus modBus";
  const queue = !usesQueue ? "" : env.loader === "neoforge"
    ? "net.neoforged.neoforge.common.NeoForge.EVENT_BUS.addListener(net.neoforged.neoforge.event.tick.ServerTickEvent.Post.class, event -> ProcedureHelpers.tickQueue());"
    : env.loader === "forge"
      ? "net.minecraftforge.common.MinecraftForge.EVENT_BUS.addListener(net.minecraftforge.eventbus.api.EventPriority.NORMAL, false, net.minecraftforge.event.TickEvent.ServerTickEvent.class, event -> {\nif (event.phase == net.minecraftforge.event.TickEvent.Phase.END) ProcedureHelpers.tickQueue();\n});"
      : "net.fabricmc.fabric.api.event.lifecycle.v1.ServerTickEvents.END_SERVER_TICK.register(server -> ProcedureHelpers.tickQueue());";
  const syncCall = `${env.modClass}Variables.syncTick`;
  const sync = !syncsVars ? "" : env.loader === "neoforge"
    ? `net.neoforged.neoforge.common.NeoForge.EVENT_BUS.addListener(net.neoforged.neoforge.event.tick.ServerTickEvent.Post.class, event -> ${syncCall}(event.getServer()));`
    : env.loader === "forge"
      ? `net.minecraftforge.common.MinecraftForge.EVENT_BUS.addListener(net.minecraftforge.eventbus.api.EventPriority.NORMAL, false, net.minecraftforge.event.TickEvent.ServerTickEvent.class, event -> {\nif (event.phase == net.minecraftforge.event.TickEvent.Phase.END) ${syncCall}(net.minecraftforge.fml.server.ServerLifecycleHooks.getCurrentServer());\n});`
      : `net.fabricmc.fabric.api.event.lifecycle.v1.ServerTickEvents.END_SERVER_TICK.register(${env.modClass}Variables::syncTick);`;
  const network = env.loader === "neoforge" ? `${env.modClass}Network.register(modBus);` : `${env.modClass}Network.register();`;
  const vars = hasPlayerVars ? `${env.modClass}Variables.register();` : "";
  return source(pkg, cls, `package ${pkg};

/** Generated by MCEdge. Registers what procedures need when the mod loads. */
public final class ${cls} {
private ${cls}() {}

public static void init(${bus}) {
${network}
${vars}
${queue}
${sync}
${triggerCode.join("\n")}
}
}`);
}

