/** Procedure class files of one compiled procedure. */
export function procedureSources(env: ProcEnv, compiled: CompiledProcedure): JavaSource[] {
  const out = [{ path: `${pkgPath(env.pkg)}/procedures/${compiled.className}.java`, code: compiled.source }];
  if (compiled.clientSource) out.push({ path: `${pkgPath(env.pkg)}/procedures/client/${compiled.className}Client.java`, code: compiled.clientSource });
  return out;
}

