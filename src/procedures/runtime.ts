/** Mixin firing HoeUseEvents when a hoe is used on a block on the server, after the block's own use passed. */
export function hoeUseMixin(pkg: string, modId: string): { id: string; code: string } {
  const mixin = "org.spongepowered.asm.mixin";
  const useOn = "useOn(Lnet/minecraft/world/item/context/UseOnContext;)Lnet/minecraft/world/InteractionResult;";
  const callback = "org.spongepowered.asm.mixin.injection.callback.CallbackInfoReturnable<net.minecraft.world.InteractionResult>";
  const code = `package ${pkg}.mixin;

/** Generated by MCEdge. Tells procedures about hoe use; ItemStack.useOn runs only when the clicked block did not use the click. */
@${mixin}.Mixin(net.minecraft.world.item.ItemStack.class)
public abstract class HoeUseMixin {
    @${mixin}.injection.Inject(method = "${useOn}", at = @${mixin}.injection.At("HEAD"), cancellable = true)
    private void ${modId}$hoeUse(net.minecraft.world.item.context.UseOnContext context, ${callback} result) {
        net.minecraft.world.item.ItemStack stack = (net.minecraft.world.item.ItemStack) (Object) this;
        if (context.getLevel().isClientSide() || context.getPlayer() == null || !stack.is(net.minecraft.tags.ItemTags.HOES)) return;
        if (${pkg}.procedures.HoeUseEvents.fire(context)) result.setReturnValue(net.minecraft.world.InteractionResult.FAIL);
    }
}
`;
  return { id: "HoeUseMixin", code };
}

/** ProcedureHelpers and ProcedureClientHelpers with the helpers the procedures use. */
export function helperSources(env: ProcEnv, used: Set<string>): JavaSource[] {
  const all = new Set(used);
  all.add("cancelEvent");
  // Client element triggers (glow, tooltip, display tick) read the client player and level through these.
  all.add("clientPlayer");
  all.add("clientLevel");
  const expand = (name: string) => {
    for (const dep of HELPERS[name]?.uses ?? []) if (!all.has(dep)) (all.add(dep), expand(dep));
  };
  [...all].forEach(expand);
  const common = [...all].filter((n) => !HELPERS[n]?.client).sort();
  const client = [...all].filter((n) => HELPERS[n]?.client).sort();
  const write = (names: string[], pkg: string, cls: string, note: string) => {
    const imports = new ImportSet(env.gen);
    const j = imports.proxy();
    const methods = names.map((name) => {
      const fn = helperCode(HELPERS[name], env.gen, env.loader);
      if (!fn) return `// ${name}: not available for ${env.loader} ${env.gen}`;
      return fn(j).replace(/^static /gm, "public static ").replace(/^private static final/gm, "private static final");
    });
    if (pkg.endsWith(".client")) imports.qualified(`${env.pkg}.procedures.ProcedureHelpers`);
    return source(pkg, cls, `package ${pkg};\n\n${imports.lines()}\n\n/** Generated by MCEdge. ${note} */\npublic final class ${cls} {\nprivate ${cls}() {}\n\n${methods.join("\n\n")}\n}`);
  };
  const out = [write(common, `${env.pkg}.procedures`, "ProcedureHelpers", "Helpers shared by the generated procedures.")];
  if (client.length) out.push(write(client, `${env.pkg}.procedures.client`, "ProcedureClientHelpers", "Client-only helpers; loaded only on the physical client."));
  return out;
}

