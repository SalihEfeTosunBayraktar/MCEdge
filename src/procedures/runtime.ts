const JAVA: Record<Transfer, Record<"legacy" | "modern", string>> = {
  number: { legacy: "double", modern: "double" },
  logic: { legacy: "boolean", modern: "boolean" },
  text: { legacy: "String", modern: "String" },
  entity: { legacy: "int", modern: "int" },
  itemstack: { legacy: "net.minecraft.item.ItemStack", modern: "net.minecraft.world.item.ItemStack" },
  blockstate: { legacy: "net.minecraft.block.BlockState", modern: "net.minecraft.world.level.block.state.BlockState" },
  direction: { legacy: "int", modern: "int" },
  tag: { legacy: "net.minecraft.nbt.CompoundNBT", modern: "net.minecraft.nbt.CompoundTag" },
};

function write(type: Transfer, value: string, legacy: boolean): string {
  switch (type) {
    case "number": return `buf.writeDouble(${value});`;
    case "logic": return `buf.writeBoolean(${value});`;
    case "text": return `buf.writeUtf(${value});`;
    case "entity":
    case "direction": return `buf.writeVarInt(${value});`;
    case "tag": return `buf.writeNbt(${value});`;
    case "itemstack": return legacy ? `buf.writeItem(${value});` : `net.minecraft.world.item.ItemStack.OPTIONAL_STREAM_CODEC.encode(buf, ${value});`;
    case "blockstate": return legacy ? `buf.writeVarInt(net.minecraft.block.Block.getId(${value}));` : `buf.writeVarInt(net.minecraft.world.level.block.Block.getId(${value}));`;
  }
}

function read(type: Transfer, legacy: boolean): string {
  switch (type) {
    case "number": return "buf.readDouble()";
    case "logic": return "buf.readBoolean()";
    case "text": return "buf.readUtf()";
    case "entity":
    case "direction": return "buf.readVarInt()";
    case "tag": return "buf.readNbt()";
    case "itemstack": return legacy ? "buf.readItem()" : "net.minecraft.world.item.ItemStack.OPTIONAL_STREAM_CODEC.decode(buf)";
    case "blockstate": return legacy ? "net.minecraft.block.Block.stateById(buf.readVarInt())" : "net.minecraft.world.level.block.Block.stateById(buf.readVarInt())";
  }
}

/** Receiver-side argument of a payload field, in a method where `level` is the receiving level. */
function receiveArg(type: Transfer, value: string, legacy: boolean): string {
  if (type === "entity") return `${value} < 0 ? null : level.getEntity(${value})`;
  if (type === "direction") return `${value} < 0 ? null : ${legacy ? "net.minecraft.util.Direction" : "net.minecraft.core.Direction"}.values()[${value}]`;
  return value;
}

export function networkSources(env: ProcEnv, segments: Segment[]): JavaSource[] {
  const legacy = env.gen === "1.16.5";
  const pkg = `${env.pkg}.procedures`;
  const cls = `${env.modClass}Network`;
  const clientCls = `${env.modClass}NetworkClient`;
  const clientPkg = `${pkg}.client`;
  const network = `${pkg}.${cls}`;
  const toClient = segments.filter((s) => s.direction === "toClient");
  const toServer = segments.filter((s) => s.direction === "toServer");
  const field = (s: Segment, name: string) => (legacy ? `p.${name}` : `p.${name}()`);
  const call = (s: Segment) => `${s.owner}.${s.method}(${["level", ...s.fields.map((f) => receiveArg(f.type, field(s, f.name), legacy))].join(", ")});`;
  const level = legacy ? "net.minecraft.world.World" : "net.minecraft.world.level.Level";
  const entity = legacy ? "net.minecraft.entity.Entity" : "net.minecraft.world.entity.Entity";
  const direction = legacy ? "net.minecraft.util.Direction" : "net.minecraft.core.Direction";
  const common = [
    `public static int id(${entity} entity) {\nreturn entity == null ? -1 : entity.getId();\n}`,
    `public static int dir(${direction} direction) {\nreturn direction == null ? -1 : direction.ordinal();\n}`,
  ];

  const payloads = segments.map((s) => {
    const comps = s.fields.map((f) => `${JAVA[f.type][legacy ? "legacy" : "modern"]} ${f.name}`);
    const encode = s.fields.map((f) => write(f.type, field(s, f.name), legacy)).join("\n");
    const decode = `new ${s.name}(${s.fields.map((f) => read(f.type, legacy)).join(", ")})`;
    if (legacy) {
      return `public static final class ${s.name} {
${s.fields.map((f) => `public final ${JAVA[f.type].legacy} ${f.name};`).join("\n")}
public ${s.name}(${comps.join(", ")}) {
${s.fields.map((f) => `this.${f.name} = ${f.name};`).join("\n")}
}
static void encode(${s.name} p, net.minecraft.network.PacketBuffer buf) {
${encode}
}
static ${s.name} decode(net.minecraft.network.PacketBuffer buf) {
return ${decode};
}
}`;
    }
    const id = rlExpr(env, `${env.modId}:${s.path}`);
    return `public record ${s.name}(${comps.join(", ")}) implements net.minecraft.network.protocol.common.custom.CustomPacketPayload {
public static final net.minecraft.network.protocol.common.custom.CustomPacketPayload.Type<${s.name}> TYPE = new net.minecraft.network.protocol.common.custom.CustomPacketPayload.Type<>(${id});
public static final net.minecraft.network.codec.StreamCodec<net.minecraft.network.RegistryFriendlyByteBuf, ${s.name}> CODEC = net.minecraft.network.codec.StreamCodec.of((buf, p) -> {
${encode}
}, buf -> ${decode});
@Override
public net.minecraft.network.protocol.common.custom.CustomPacketPayload.Type<${s.name}> type() {
return TYPE;
}
}`;
  });

  const serverHandlers = toServer.map((s) => `static void handle${s.name}(${s.name} p, ${legacy ? "net.minecraft.entity.player.PlayerEntity" : "net.minecraft.world.entity.player.Player"} player) {
if (player == null) return;
${level} level = ${legacy ? "player.level" : "player.level()"};
${call(s)}
}`);
  const clientHandlers = toClient.map((s) => `public static void handle${s.name}(${network}.${s.name} p) {
${level} level = net.minecraft.client.Minecraft.getInstance().level;
if (level == null) return;
${call(s).replace(/^/, "")}
}`);

  let register: string;
  let send: string[];
  let clientRegister = "";
  let toServerSend: string;
  if (env.loader === "neoforge") {
    const modern26 = env.gen === "26.3";
    register = `public static void register(net.neoforged.bus.api.IEventBus modBus) {
modBus.addListener(net.neoforged.neoforge.network.event.RegisterPayloadHandlersEvent.class, event -> {
net.neoforged.neoforge.network.registration.PayloadRegistrar registrar = event.registrar("1");
${toClient.map((s) => modern26 ? `registrar.playToClient(${s.name}.TYPE, ${s.name}.CODEC);` : `registrar.playToClient(${s.name}.TYPE, ${s.name}.CODEC, (payload, context) -> ${clientPkg}.${clientCls}.handle${s.name}(payload));`).join("\n")}
${toServer.map((s) => `registrar.playToServer(${s.name}.TYPE, ${s.name}.CODEC, (payload, context) -> handle${s.name}(payload, context.player()));`).join("\n")}
});
}`;
    send = [
      `public static void toClients(net.minecraft.world.level.LevelAccessor world, net.minecraft.network.protocol.common.custom.CustomPacketPayload payload) {\nif (world instanceof net.minecraft.server.level.ServerLevel level) net.neoforged.neoforge.network.PacketDistributor.sendToPlayersInDimension(level, payload);\n}`,
      `public static void toPlayer(net.minecraft.world.entity.Entity entity, net.minecraft.network.protocol.common.custom.CustomPacketPayload payload) {\nif (entity instanceof net.minecraft.server.level.ServerPlayer player) net.neoforged.neoforge.network.PacketDistributor.sendToPlayer(player, payload);\n}`,
    ];
    toServerSend = modern26 ? "net.neoforged.neoforge.client.network.ClientPacketDistributor.sendToServer(payload);" : "net.neoforged.neoforge.network.PacketDistributor.sendToServer(payload);";
    if (modern26 && toClient.length) {
      clientRegister = `public static void register(net.neoforged.bus.api.IEventBus modBus) {
modBus.addListener(net.neoforged.neoforge.client.network.event.RegisterClientPayloadHandlersEvent.class, event -> {
${toClient.map((s) => `event.register(${network}.${s.name}.TYPE, (payload, context) -> handle${s.name}(payload));`).join("\n")}
});
}`;
    } else clientRegister = "public static void register(net.neoforged.bus.api.IEventBus modBus) {\n}";
  } else if (env.loader === "fabric") {
    const s2c = env.gen === "26.3" ? "clientboundPlay" : "playS2C";
    const c2s = env.gen === "26.3" ? "serverboundPlay" : "playC2S";
    register = `public static void register() {
${toClient.map((s) => `net.fabricmc.fabric.api.networking.v1.PayloadTypeRegistry.${s2c}().register(${s.name}.TYPE, ${s.name}.CODEC);`).join("\n")}
${toServer.map((s) => `net.fabricmc.fabric.api.networking.v1.PayloadTypeRegistry.${c2s}().register(${s.name}.TYPE, ${s.name}.CODEC);\nnet.fabricmc.fabric.api.networking.v1.ServerPlayNetworking.registerGlobalReceiver(${s.name}.TYPE, (payload, context) -> context.server().execute(() -> handle${s.name}(payload, context.player())));`).join("\n")}
}`;
    send = [
      `public static void toClients(net.minecraft.world.level.LevelAccessor world, net.minecraft.network.protocol.common.custom.CustomPacketPayload payload) {\nif (world instanceof net.minecraft.server.level.ServerLevel level) for (net.minecraft.server.level.ServerPlayer player : level.players()) net.fabricmc.fabric.api.networking.v1.ServerPlayNetworking.send(player, payload);\n}`,
      `public static void toPlayer(net.minecraft.world.entity.Entity entity, net.minecraft.network.protocol.common.custom.CustomPacketPayload payload) {\nif (entity instanceof net.minecraft.server.level.ServerPlayer player) net.fabricmc.fabric.api.networking.v1.ServerPlayNetworking.send(player, payload);\n}`,
    ];
    toServerSend = "net.fabricmc.fabric.api.client.networking.v1.ClientPlayNetworking.send(payload);";
    clientRegister = `public static void register() {
${toClient.map((s) => `net.fabricmc.fabric.api.client.networking.v1.ClientPlayNetworking.registerGlobalReceiver(${network}.${s.name}.TYPE, (payload, context) -> context.client().execute(() -> handle${s.name}(payload)));`).join("\n")}
}`;
  } else {
    register = `private static final String VERSION = "1";
public static final net.minecraftforge.fml.network.simple.SimpleChannel CHANNEL = net.minecraftforge.fml.network.NetworkRegistry.newSimpleChannel(${rlExpr(env, `${env.modId}:procedures`)}, () -> VERSION, VERSION::equals, VERSION::equals);
public static void register() {
int id = 0;
${toClient.map((s) => `CHANNEL.registerMessage(id++, ${s.name}.class, ${s.name}::encode, ${s.name}::decode, (p, context) -> {
context.get().enqueueWork(() -> net.minecraftforge.fml.DistExecutor.unsafeRunWhenOn(net.minecraftforge.api.distmarker.Dist.CLIENT, () -> () -> ${clientPkg}.${clientCls}.handle${s.name}(p)));
context.get().setPacketHandled(true);
});`).join("\n")}
${toServer.map((s) => `CHANNEL.registerMessage(id++, ${s.name}.class, ${s.name}::encode, ${s.name}::decode, (p, context) -> {
net.minecraft.entity.player.ServerPlayerEntity player = context.get().getSender();
context.get().enqueueWork(() -> handle${s.name}(p, player));
context.get().setPacketHandled(true);
});`).join("\n")}
}`;
    send = [
      `public static void toClients(net.minecraft.world.IWorld world, Object payload) {\nif (world instanceof net.minecraft.world.server.ServerWorld) CHANNEL.send(net.minecraftforge.fml.network.PacketDistributor.DIMENSION.with(() -> ((net.minecraft.world.server.ServerWorld) world).dimension()), payload);\n}`,
      `public static void toPlayer(net.minecraft.entity.Entity entity, Object payload) {\nif (entity instanceof net.minecraft.entity.player.ServerPlayerEntity) CHANNEL.send(net.minecraftforge.fml.network.PacketDistributor.PLAYER.with(() -> (net.minecraft.entity.player.ServerPlayerEntity) entity), payload);\n}`,
    ];
    toServerSend = `${network}.CHANNEL.sendToServer(payload);`;
    clientRegister = "public static void register() {\n}";
  }
  const payloadType = env.loader === "forge" ? "Object" : "net.minecraft.network.protocol.common.custom.CustomPacketPayload";
  const main = source(pkg, cls, `package ${pkg};

/** Generated by MCEdge. Packets of procedures that switch between server and client. */
public final class ${cls} {
private ${cls}() {}

${[...payloads, register, ...send, ...common, ...serverHandlers].join("\n\n")}
}`);
  const client = source(clientPkg, clientCls, `package ${clientPkg};

/** Generated by MCEdge. Client side of the procedure packets; loaded only on the physical client. */
public final class ${clientCls} {
private ${clientCls}() {}

${clientRegister}

public static void toServer(${payloadType} payload) {
${toServerSend}
}

${clientHandlers.join("\n\n")}
}`);
  return [main, client];
}

