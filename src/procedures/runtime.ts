/** Statements reading / writing a variable from a CompoundTag `tag`. */
function tagRead(v: GlobalVar & { initial: string }, gen: Gen, registries: string): string {
  const legacy = gen === "1.16.5";
  const k = JSON.stringify(v.name);
  switch (v.type) {
    case "number": return legacy ? `tag.contains(${k}) ? tag.getDouble(${k}) : ${initial(v, gen)}` : `tag.getDoubleOr(${k}, ${initial(v, gen)})`;
    case "logic": return legacy ? `tag.contains(${k}) ? tag.getBoolean(${k}) : ${initial(v, gen)}` : `tag.getBooleanOr(${k}, ${initial(v, gen)})`;
    case "direction": return legacy
      ? `tag.contains(${k}) ? net.minecraft.util.Direction.byName(tag.getString(${k})) : ${initial(v, gen)}`
      : `tag.contains(${k}) ? net.minecraft.core.Direction.byName(tag.getStringOr(${k}, "north")) : ${initial(v, gen)}`;
    case "itemstack": return legacy
      ? `tag.contains(${k}) ? net.minecraft.item.ItemStack.of(tag.getCompound(${k})) : ${initial(v, gen)}`
      : `tag.contains(${k}) ? net.minecraft.world.item.ItemStack.OPTIONAL_CODEC.parse(${registries}.createSerializationContext(net.minecraft.nbt.NbtOps.INSTANCE), tag.get(${k})).result().orElse(net.minecraft.world.item.ItemStack.EMPTY) : ${initial(v, gen)}`;
    case "blockstate": return legacy
      ? `tag.contains(${k}) ? net.minecraft.nbt.NBTUtil.readBlockState(tag.getCompound(${k})) : ${initial(v, gen)}`
      : `tag.contains(${k}) ? net.minecraft.nbt.NbtUtils.readBlockState(net.minecraft.core.registries.BuiltInRegistries.BLOCK, tag.getCompoundOrEmpty(${k})) : ${initial(v, gen)}`;
    default: return legacy ? `tag.contains(${k}) ? tag.getString(${k}) : ${initial(v, gen)}` : `tag.getStringOr(${k}, ${initial(v, gen)})`;
  }
}

function tagWrite(v: GlobalVar, gen: Gen, registries: string): string {
  const legacy = gen === "1.16.5";
  const k = JSON.stringify(v.name);
  switch (v.type) {
    case "number": return `tag.putDouble(${k}, value);`;
    case "logic": return `tag.putBoolean(${k}, value);`;
    case "direction": return `if (value != null) tag.putString(${k}, value.getName());`;
    case "itemstack": return legacy
      ? `tag.put(${k}, value.save(new net.minecraft.nbt.CompoundNBT()));`
      : `net.minecraft.world.item.ItemStack.OPTIONAL_CODEC.encodeStart(${registries}.createSerializationContext(net.minecraft.nbt.NbtOps.INSTANCE), value).result().ifPresent(t -> tag.put(${k}, t));`;
    case "blockstate": return legacy ? `tag.put(${k}, net.minecraft.nbt.NBTUtil.writeBlockState(value));` : `tag.put(${k}, net.minecraft.nbt.NbtUtils.writeBlockState(value));`;
    default: return `tag.putString(${k}, value == null ? "" : value);`;
  }
}

function initial(v: GlobalVar & { initial: string }, gen: Gen): string {
  const legacy = gen === "1.16.5";
  switch (v.type) {
    case "number": { const n = Number(v.initial); return Number.isFinite(n) ? `${n}D` : "0D"; }
    case "logic": return v.initial === "true" ? "true" : "false";
    case "direction": return `${legacy ? "net.minecraft.util.Direction" : "net.minecraft.core.Direction"}.${["north", "south", "east", "west", "up", "down"].includes(v.initial.toLowerCase()) ? v.initial.toUpperCase() : "NORTH"}`;
    case "itemstack": return `${legacy ? "net.minecraft.item.ItemStack" : "net.minecraft.world.item.ItemStack"}.EMPTY`;
    case "blockstate": return `${legacy ? "net.minecraft.block.Blocks" : "net.minecraft.world.level.block.Blocks"}.AIR.defaultBlockState()`;
    default: return JSON.stringify(v.initial ?? "");
  }
}

const JTYPE: Record<string, Record<"legacy" | "modern", string>> = {
  number: { legacy: "double", modern: "double" },
  logic: { legacy: "boolean", modern: "boolean" },
  text: { legacy: "String", modern: "String" },
  itemstack: { legacy: "net.minecraft.item.ItemStack", modern: "net.minecraft.world.item.ItemStack" },
  blockstate: { legacy: "net.minecraft.block.BlockState", modern: "net.minecraft.world.level.block.state.BlockState" },
  direction: { legacy: "net.minecraft.util.Direction", modern: "net.minecraft.core.Direction" },
};

/** <Mod>Variables: session values in static fields, world and map values in saved data, player values on the player. */
export function variablesSource(env: ProcEnv, vars: (GlobalVar & { initial: string; scope: string })[]): JavaSource {
  const legacy = env.gen === "1.16.5";
  const pkg = `${env.pkg}.procedures`;
  const cls = `${env.modClass}Variables`;
  const T = (v: GlobalVar) => JTYPE[v.type][legacy ? "legacy" : "modern"];
  const compound = legacy ? "net.minecraft.nbt.CompoundNBT" : "net.minecraft.nbt.CompoundTag";
  const world = legacy ? "net.minecraft.world.IWorld" : "net.minecraft.world.level.LevelAccessor";
  const entity = legacy ? "net.minecraft.entity.Entity" : "net.minecraft.world.entity.Entity";
  const serverPlayer = legacy ? "net.minecraft.entity.player.ServerPlayerEntity" : "net.minecraft.server.level.ServerPlayer";
  const members: string[] = [];
  for (const v of vars) {
    const scope = v.scope;
    if (scope === "global_session") {
      members.push(`private static ${T(v)} ${v.name} = ${initial(v, env.gen)};
public static ${T(v)} get_${v.name}() {
return ${v.name};
}
public static void set_${v.name}(${T(v)} value) {
${v.name} = value;
}`);
    } else if (v.world) {
      const map = scope === "global_map";
      const reg = legacy ? "" : "data.registries";
      members.push(`public static ${T(v)} get_${v.name}(${world} world) {
Data data = data(world, ${map});
if (data == null) return ${initial(v, env.gen)};
${compound} tag = data.tag;
return ${tagRead(v, env.gen, reg)};
}
public static void set_${v.name}(${world} world, ${T(v)} value) {
Data data = data(world, ${map});
if (data == null) return;
${compound} tag = data.tag;
${tagWrite(v, env.gen, reg)}
data.setDirty();
if (!world.isClientSide()) ${map ? "mapDirty = true" : "worldDirty.add(world)"};
}`);
    } else {
      const persistent = scope === "player_persistent";
      const reg = "entity.registryAccess()";
      members.push(`public static ${T(v)} get_${v.name}(${entity} entity) {
if (entity == null) return ${initial(v, env.gen)};
${compound} tag = playerTag(entity, ${persistent});
return ${tagRead(v, env.gen, reg)};
}
public static void set_${v.name}(${entity} entity, ${T(v)} value) {
if (entity == null) return;
${compound} tag = playerTag(entity, ${persistent});
${tagWrite(v, env.gen, reg)}
savePlayerTag(entity, ${persistent}, tag);
if (entity instanceof ${serverPlayer}) dirtyPlayers.add((${serverPlayer}) entity);
}`);
    }
  }
  const hasWorld = vars.some((v) => v.world);
  const hasPlayer = vars.some((v) => v.player);
  if (hasWorld) members.push(worldData(env));
  if (hasPlayer) members.push(playerData(env, vars));
  else members.push("public static void register() {\n}");
  if (hasWorld || hasPlayer) members.push(clientSync(env, hasWorld, hasPlayer));
  return source(pkg, cls, `package ${pkg};

/** Generated by MCEdge. Global and player variables of the project (variables.json). */
public final class ${cls} {
private ${cls}() {}

${members.join("\n\n")}
}`);
}

/** Name of the packet carrying a variable tag to the client. */
export const SYNC_SEGMENT = "VariablesSync";
const SYNC_SCOPES = { persistent: 0, lifetime: 1, map: 2, world: 3 };

/**
 * Keeps variables readable on the client: the server sends a tag of the scopes that changed at the end of the tick
 * (one packet however many variables a procedure set), and everything when a player appears in a level (join,
 * respawn and dimension change all do that, on every loader).
 */
function clientSync(env: ProcEnv, hasWorld: boolean, hasPlayer: boolean): string {
  const legacy = env.gen === "1.16.5";
  const tag = legacy ? "net.minecraft.nbt.CompoundNBT" : "net.minecraft.nbt.CompoundTag";
  const player = legacy ? "net.minecraft.entity.player.ServerPlayerEntity" : "net.minecraft.server.level.ServerPlayer";
  const level = legacy ? "player.level" : "player.level()";
  const levelType = legacy ? "net.minecraft.world.World" : "net.minecraft.world.level.Level";
  const worldType = legacy ? "net.minecraft.world.IWorld" : "net.minecraft.world.level.LevelAccessor";
  const net = `${env.modClass}Network`;
  const packet = (scope: number, value: string) => `new ${net}.${SYNC_SEGMENT}(${scope}, ${value})`;
  const fields = [`private static final java.util.Map<${player}, ${levelType}> synced = new java.util.WeakHashMap<>();`];
  const receive: string[] = [];
  let flush = `public static void flush(${player} player) {\n}`;
  if (hasPlayer) {
    fields.push(`private static ${tag} clientPersistent = new ${tag}();`, `private static ${tag} clientLifetime = new ${tag}();`,
      `private static final java.util.Set<${player}> dirtyPlayers = java.util.Collections.newSetFromMap(new java.util.WeakHashMap<>());`);
    flush = `/** Sends the player's variables now, for code whose next packet needs them (opening a GUI). */
public static void flush(${player} player) {
dirtyPlayers.remove(player);
${net}.toPlayer(player, ${packet(SYNC_SCOPES.persistent, "playerTag(player, true)")});
${net}.toPlayer(player, ${packet(SYNC_SCOPES.lifetime, "playerTag(player, false)")});
}`;
    receive.push(`if (scope == ${SYNC_SCOPES.persistent}) clientPersistent = tag;`, `if (scope == ${SYNC_SCOPES.lifetime}) clientLifetime = tag;`);
  }
  if (hasWorld) {
    fields.push("private static final Data clientMap = new Data();", "private static final Data clientWorld = new Data();", "private static boolean mapDirty;",
      `private static final java.util.Set<${worldType}> worldDirty = new java.util.HashSet<>();`);
    receive.push(`if (scope == ${SYNC_SCOPES.map}) clientMap.tag = tag;`, `if (scope == ${SYNC_SCOPES.world}) clientWorld.tag = tag;`);
  }
  const fresh = [
    ...(hasPlayer ? ["flush(player);"] : []),
    ...(hasWorld ? [`${net}.toPlayer(player, ${packet(SYNC_SCOPES.map, `data(${level}, true).tag`)});`, `${net}.toPlayer(player, ${packet(SYNC_SCOPES.world, `data(${level}, false).tag`)});`] : []),
  ];
  const tick = [`for (${player} player : server.getPlayerList().getPlayers()) {
if (synced.put(player, ${level}) != ${level}) {
${fresh.join("\n")}
}${hasPlayer ? " else if (dirtyPlayers.contains(player)) {\nflush(player);\n}" : ""}
}`];
  if (hasWorld) tick.push(`if (mapDirty) {
mapDirty = false;
for (${player} player : server.getPlayerList().getPlayers()) ${net}.toPlayer(player, ${packet(SYNC_SCOPES.map, `data(${level}, true).tag`)});
}
for (${worldType} world : worldDirty) ${net}.toClients(world, ${packet(SYNC_SCOPES.world, "data(world, false).tag")});
worldDirty.clear();`);
  return `${fields.join("\n")}
${flush}
public static void syncTick(net.minecraft.server.MinecraftServer server) {
if (server == null) return;
${tick.join("\n")}
}
/** Client side: a tag from the server. */
public static void receive(${levelType} level, double scope, ${tag} tag) {
${receive.join("\n")}
}`;
}

