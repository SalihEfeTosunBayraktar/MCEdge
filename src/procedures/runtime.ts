/**
 * Java sources every mod with procedures gets, per engine: the helper classes, the network packets of side
 * switches (payload, registration and handlers in both directions), the trigger registrations and the global
 * variable storage. Procedure classes themselves come from compile.ts.
 */

export interface JavaSource {
  /** Path under src/main/java ("dev/example/procedures/ProcedureHelpers.java"). */
  path: string;
  code: string;
}

const pkgPath = (pkg: string) => pkg.replaceAll(".", "/");
const source = (pkg: string, cls: string, code: string): JavaSource => ({ path: `${pkgPath(pkg)}/${cls}.java`, code: reindent(code) + "\n" });

