/** Listeners of the Fabric block place trigger; fired by the mixin of blockPlaceMixin. */
export function blockPlaceEventsSource(pkg: string): JavaSource {
  return source(`${pkg}.procedures`, "BlockPlaceEvents", `package ${pkg}.procedures;

/** Generated by MCEdge. Fabric API has no block place event; this is the one procedures listen to. */
public final class BlockPlaceEvents {
public interface Listener {
/** True cancels the placement. */
boolean placed(net.minecraft.world.level.Level world, net.minecraft.core.BlockPos pos, net.minecraft.world.level.block.state.BlockState state, net.minecraft.world.entity.Entity entity);
}

public static final java.util.List<Listener> LISTENERS = new java.util.ArrayList<>();

private BlockPlaceEvents() {}

/** Runs the listeners; a cancelled placement puts back what was there, and the item unless the player is in creative. */
public static void fire(net.minecraft.world.item.context.BlockPlaceContext context, net.minecraft.world.level.block.state.BlockState replaced) {
net.minecraft.world.level.Level world = context.getLevel();
net.minecraft.core.BlockPos pos = context.getClickedPos();
net.minecraft.world.level.block.state.BlockState state = world.getBlockState(pos);
boolean cancelled = false;
for (Listener listener : LISTENERS) cancelled |= listener.placed(world, pos, state, context.getPlayer());
if (!cancelled) return;
world.setBlock(pos, replaced, 3);
if (context.getPlayer() != null && !context.getPlayer().getAbilities().instabuild) context.getItemInHand().grow(1);
}
}`);
}

/** Mixin firing BlockPlaceEvents after a block item placed its block on the server. */
export function blockPlaceMixin(pkg: string, modId: string): { id: string; code: string } {
  const mixin = "org.spongepowered.asm.mixin";
  const place = "place(Lnet/minecraft/world/item/context/BlockPlaceContext;)Lnet/minecraft/world/InteractionResult;";
  const callback = "org.spongepowered.asm.mixin.injection.callback.CallbackInfoReturnable<net.minecraft.world.InteractionResult>";
  const code = `package ${pkg}.mixin;

/** Generated by MCEdge. Tells procedures about placed blocks; the state before is kept so a procedure can cancel. */
@${mixin}.Mixin(net.minecraft.world.item.BlockItem.class)
public abstract class BlockPlaceMixin {
    @${mixin}.Unique
    private static final ThreadLocal<net.minecraft.world.level.block.state.BlockState> ${modId}$replaced = new ThreadLocal<>();

    @${mixin}.injection.Inject(method = "${place}", at = @${mixin}.injection.At("HEAD"))
    private void ${modId}$beforePlace(net.minecraft.world.item.context.BlockPlaceContext context, ${callback} result) {
        ${modId}$replaced.set(context.getLevel().getBlockState(context.getClickedPos()));
    }

    @${mixin}.injection.Inject(method = "${place}", at = @${mixin}.injection.At("RETURN"))
    private void ${modId}$afterPlace(net.minecraft.world.item.context.BlockPlaceContext context, ${callback} result) {
        if (!context.getLevel().isClientSide() && result.getReturnValue().consumesAction()) ${pkg}.procedures.BlockPlaceEvents.fire(context, ${modId}$replaced.get());
    }
}
`;
  return { id: "BlockPlaceMixin", code };
}

