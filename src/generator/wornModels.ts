import { idExpr, itemExpr, jstr } from "./java.ts";
import { boneNames, modelClass } from "./mob/models.ts";
import { modClassName } from "./registries.ts";
import type { GenEnv, JavaSourceFile } from "./typeModule.ts";

/**
 * Custom worn armor models: a Blockbench Java model (models/<name>.java) whose named parts are attached to the
 * wearer's head, body, arms and legs, drawn with their own texture instead of the vanilla armor shape, like
 * MCreator does. Each attached part takes the pose of the body part it is attached to (its own pivot is dropped).
 *
 * 1.16.5: the armor item returns a BipedModel made of those parts (Forge's getArmorModel) and its texture. 1.21.5
 * and 26.3 build a HumanoidModel from them: Fabric draws it from an ArmorRenderer, NeoForge from a render layer on
 * every humanoid renderer (the vanilla equipment layer is told to skip the item). Translucent pieces use the
 * translucent entity render type.
 */

/** Body parts of the humanoid model a custom part can be attached to. */
export const SLOTS = ["head", "body", "rightArm", "leftArm", "rightLeg", "leftLeg"] as const;
export type Slot = (typeof SLOTS)[number];

export interface WornPiece {
  /** Registry name of the armor item ("ruby_armor_helmet"). */
  pieceId: string;
  /** Project model name (models/<name>.java). */
  model: string;
  /** Index of the model bone (BONE_NAMES) attached to each body part. */
  parts: Partial<Record<Slot, number>>;
  /** Texture path under assets/<modid>/textures, without .png ("entity/armor/ruby_armor_helmet"). */
  texture: string;
  translucent: boolean;
}

/** Bone index of a part name (any case), or undefined with a warning. */
export function boneIndex(env: GenEnv, model: string, part: string, warn: (t: string) => void): number | undefined {
  if (!part) return undefined;
  const names = boneNames(env, model);
  const i = names.findIndex((n) => n.toLowerCase() === part.toLowerCase());
  if (i < 0) warn(`model "${model}" has no part "${part}" (parts: ${names.join(", ")})`);
  return i < 0 ? undefined : i;
}

export const wornModelsClass = (env: GenEnv) => `${env.project.mod.package}.client.${modClassName(env)}WornModels`;
const fieldName = (p: WornPiece) => p.pieceId.toUpperCase();
const textureId = (env: GenEnv, p: WornPiece) => `${env.modId}:textures/${p.texture}.png`;

/** 1.16.5 armor item members: the custom model and its texture. */
export function legacyWornMembers(env: GenEnv, p: WornPiece): string {
  return `
    @net.minecraftforge.api.distmarker.OnlyIn(net.minecraftforge.api.distmarker.Dist.CLIENT)
    @Override
    @SuppressWarnings("unchecked")
    public <A extends net.minecraft.client.renderer.entity.model.BipedModel<?>> A getArmorModel(net.minecraft.entity.LivingEntity entity, net.minecraft.item.ItemStack stack, net.minecraft.inventory.EquipmentSlotType slot, A defaultModel) {
        return (A) ${wornModelsClass(env)}.${fieldName(p).toLowerCase()}();
    }

    @Override
    public String getArmorTexture(net.minecraft.item.ItemStack stack, net.minecraft.entity.Entity entity, net.minecraft.inventory.EquipmentSlotType slot, String type) {
        return ${jstr(textureId(env, p))};
    }
`;
}

/** The <Mod>WornModels client class. */
export function wornModelsSource(env: GenEnv, pieces: WornPiece[]): JavaSourceFile {
  const cls = wornModelsClass(env);
  const pkg = cls.slice(0, cls.lastIndexOf("."));
  const name = cls.slice(cls.lastIndexOf(".") + 1);
  const code = env.mc === "1.16.5" ? legacySource(env, pkg, name, pieces) : modernSource(env, pkg, name, pieces);
  return { path: `${pkg.replaceAll(".", "/")}/${name}.java`, code };
}

function legacySource(env: GenEnv, pkg: string, name: string, pieces: WornPiece[]): string {
  const R = "net.minecraft.client.renderer.model.ModelRenderer";
  const B = "net.minecraft.client.renderer.entity.model.BipedModel<net.minecraft.entity.LivingEntity>";
  const getters = pieces.map((p) => {
    const M = modelClass(env, p.model);
    const part = (s: Slot) => (p.parts[s] === undefined ? "null" : `model.bones[${p.parts[s]}]`);
    return `    private static ${B} ${fieldName(p)};

    public static ${B} ${fieldName(p).toLowerCase()}() {
        if (${fieldName(p)} == null) {
            ${M}<net.minecraft.entity.LivingEntity> model = new ${M}<>();
            ${fieldName(p)} = biped(${SLOTS.map(part).join(", ")}, ${p.translucent ? idExpr(env, textureId(env, p)) : "null"});
        }
        return ${fieldName(p)};
    }`;
  });
  return `package ${pkg};

/** Generated by MCEdge: custom worn armor models. */
public final class ${name} {
    private ${name}() {}

${getters.join("\n\n")}

    /** A biped model whose head, body, arms and legs hold the given parts; a translucent texture draws see-through. */
    private static ${B} biped(${R} head, ${R} body, ${R} rightArm, ${R} leftArm, ${R} rightLeg, ${R} leftLeg, net.minecraft.util.ResourceLocation translucent) {
        ${B} model = new net.minecraft.client.renderer.entity.model.BipedModel<net.minecraft.entity.LivingEntity>(0.0F) {
            @Override
            public void renderToBuffer(com.mojang.blaze3d.matrix.MatrixStack pose, com.mojang.blaze3d.vertex.IVertexBuilder buffer, int light, int overlay, float red, float green, float blue, float alpha) {
                com.mojang.blaze3d.vertex.IVertexBuilder target = translucent == null ? buffer
                    : net.minecraft.client.Minecraft.getInstance().renderBuffers().bufferSource().getBuffer(net.minecraft.client.renderer.RenderType.entityTranslucent(translucent));
                super.renderToBuffer(pose, target, light, overlay, red, green, blue, alpha);
            }
        };
        model.head = slot(model, head);
        model.hat = new ${R}(model);
        model.body = slot(model, body);
        model.rightArm = slot(model, rightArm);
        model.leftArm = slot(model, leftArm);
        model.rightLeg = slot(model, rightLeg);
        model.leftLeg = slot(model, leftLeg);
        return model;
    }

    /** A body part holding the custom part at its pivot; the vanilla layer copies the wearer's pose onto it. */
    private static ${R} slot(net.minecraft.client.renderer.model.Model owner, ${R} part) {
        ${R} slot = new ${R}(owner);
        if (part != null) {
            part.setPos(0.0F, 0.0F, 0.0F);
            part.xRot = 0.0F;
            part.yRot = 0.0F;
            part.zRot = 0.0F;
            slot.addChild(part);
        }
        return slot;
    }
}
`;
}

function modernSource(env: GenEnv, pkg: string, name: string, pieces: WornPiece[]): string {
  const v26 = env.mc === "26.3";
  const P = "net.minecraft.client.model.geom.ModelPart";
  const PP = "net.minecraft.client.model.geom.PartPose";
  const S = "net.minecraft.client.renderer.entity.state.HumanoidRenderState";
  const H = `net.minecraft.client.model.HumanoidModel<${S}>`;
  const types = v26 ? "net.minecraft.client.renderer.rendertype.RenderTypes" : "net.minecraft.client.renderer.RenderType";
  const RT = v26 ? "net.minecraft.client.renderer.rendertype.RenderType" : "net.minecraft.client.renderer.RenderType";
  const stack = "net.minecraft.world.item.ItemStack";
  const lookups = pieces.map((p) => {
    const M = modelClass(env, p.model);
    const part = (s: Slot) => (p.parts[s] === undefined ? "null" : `model.bones[${p.parts[s]}]`);
    return `        if (stack.is(${itemExpr(env, p.pieceId)})) {
            if (${fieldName(p)} == null) {
                ${M} model = new ${M}(${M}.createBodyLayer().bakeRoot());
                ${fieldName(p)} = new Worn(humanoid(${SLOTS.map(part).join(", ")}), ${types}.${p.translucent ? "entityTranslucent" : "armorCutoutNoCull"}(${idExpr(env, textureId(env, p))}));
            }
            return ${fieldName(p)};
        }`;
  });
  const items = pieces.map((p) => itemExpr(env, p.pieceId)).join(", ");
  const ext = "net.neoforged.neoforge.client.extensions.common";
  // Registration: Fabric draws the pieces itself; NeoForge skips them in the equipment layer and adds a layer.
  const register = env.loader === "fabric"
    ? `net.fabricmc.fabric.api.client.rendering.v1.ArmorRenderer.register(${v26
      ? `(pose, collector, stack, state, slot, light, context) -> {
            Worn worn = worn(stack);
            if (worn != null) net.fabricmc.fabric.api.client.rendering.v1.ArmorRenderer.submitTransformCopyingModel(context, state, worn.model(), state, false, collector, pose, worn.type(), light, net.minecraft.client.renderer.texture.OverlayTexture.NO_OVERLAY, state.outlineColor);
        }`
      : `(pose, buffers, stack, state, slot, light, context) -> {
            Worn worn = worn(stack);
            if (worn == null) return;
            copyPose(context, worn.model());
            worn.model().renderToBuffer(pose, buffers.getBuffer(worn.type()), light, net.minecraft.client.renderer.texture.OverlayTexture.NO_OVERLAY);
        }`}, ${items});`
    : `modBus.addListener(${ext}.RegisterClientExtensionsEvent.class, event -> event.registerItem(new ${ext}.IClientItemExtensions() {
            @Override
            public int getArmorLayerTintColor(${stack} stack, net.minecraft.client.resources.model.EquipmentClientInfo.Layer layer, int layerIdx, int fallbackColor) {
                return 0;
            }
        }, ${items}));
        modBus.addListener(net.neoforged.neoforge.client.event.EntityRenderersEvent.AddLayers.class, ${name}::addLayers);`;
  const layer = env.loader === "fabric" ? "" : `

    private static void addLayers(net.neoforged.neoforge.client.event.EntityRenderersEvent.AddLayers event) {
        for (net.minecraft.world.entity.EntityType<?> type : event.getEntityTypes()) addLayer(event.getRenderer(type));
        for (${v26 ? "net.minecraft.world.entity.player.PlayerModelType" : "net.minecraft.client.resources.PlayerSkin.Model"} skin : event.getSkins()) addLayer(event.${v26 ? "getPlayerRenderer" : "getSkin"}(skin));
    }

    @SuppressWarnings({"rawtypes", "unchecked"})
    private static void addLayer(Object renderer) {
        if (renderer instanceof net.minecraft.client.renderer.entity.LivingEntityRenderer living && living.getModel() instanceof net.minecraft.client.model.HumanoidModel) {
            living.addLayer(new Layer(living));
        }
    }

    /** Draws the custom worn pieces of a humanoid in the pose of its body. */
    private static final class Layer extends net.minecraft.client.renderer.entity.layers.RenderLayer<${S}, ${H}> {
        Layer(net.minecraft.client.renderer.entity.RenderLayerParent<${S}, ${H}> parent) {
            super(parent);
        }

        @Override
        ${v26
    ? `public void submit(com.mojang.blaze3d.vertex.PoseStack pose, net.minecraft.client.renderer.SubmitNodeCollector collector, int light, ${S} state, float yRot, float xRot) {
            for (${stack} stack : new ${stack}[] {state.headEquipment, state.chestEquipment, state.legsEquipment, state.feetEquipment}) {
                Worn worn = worn(stack);
                if (worn != null) collector.submitModel(new Posed(this.getParentModel(), worn.model()), state, pose, worn.type(), light, net.minecraft.client.renderer.texture.OverlayTexture.NO_OVERLAY, state.outlineColor);
            }
        }`
    : `public void render(com.mojang.blaze3d.vertex.PoseStack pose, net.minecraft.client.renderer.MultiBufferSource buffers, int light, ${S} state, float yRot, float xRot) {
            for (${stack} stack : new ${stack}[] {state.headEquipment, state.chestEquipment, state.legsEquipment, state.feetEquipment}) {
                Worn worn = worn(stack);
                if (worn == null) continue;
                copyPose(this.getParentModel(), worn.model());
                worn.model().renderToBuffer(pose, buffers.getBuffer(worn.type()), light, net.minecraft.client.renderer.texture.OverlayTexture.NO_OVERLAY);
            }
        }`}
    }${v26 ? `

    /** The custom model posed like the wearer's body when it is drawn (rendering happens after submitting). */
    private static final class Posed extends net.minecraft.client.model.Model<${S}> {
        private final net.minecraft.client.model.HumanoidModel<?> source;
        private final ${H} target;

        Posed(net.minecraft.client.model.HumanoidModel<?> source, ${H} target) {
            super(target.root(), ${types}::entityCutout);
            this.source = source;
            this.target = target;
        }

        @Override
        @SuppressWarnings({"rawtypes", "unchecked"})
        public void setupAnim(${S} state) {
            ((net.minecraft.client.model.HumanoidModel) this.source).setupAnim(state);
            copyPose(this.source, this.target);
        }
    }` : ""}`;
  return `package ${pkg};

/** Generated by MCEdge: custom worn armor models. */
public final class ${name} {
    private ${name}() {}

    /** A worn piece: its humanoid model and render type. */
    private record Worn(${H} model, ${RT} type) {}

${pieces.map((p) => `    private static Worn ${fieldName(p)};`).join("\n")}

    /** The custom worn model of an armor stack, or null when it has none. */
    static Worn worn(${stack} stack) {
${lookups.join("\n")}
        return null;
    }

    public static void register(${env.loader === "fabric" ? "" : "net.neoforged.bus.api.IEventBus modBus"}) {
        ${register}
    }${layer}

    /** Copies the pose of the wearer's body parts. */
    static void copyPose(net.minecraft.client.model.HumanoidModel<?> from, net.minecraft.client.model.HumanoidModel<?> to) {
        to.head.loadPose(from.head.storePose());
        to.body.loadPose(from.body.storePose());
        to.rightArm.loadPose(from.rightArm.storePose());
        to.leftArm.loadPose(from.leftArm.storePose());
        to.rightLeg.loadPose(from.rightLeg.storePose());
        to.leftLeg.loadPose(from.leftLeg.storePose());
    }

    /** A humanoid model whose head, body, arms and legs hold the given parts at their pivots. */
    private static ${H} humanoid(${P} head, ${P} body, ${P} rightArm, ${P} leftArm, ${P} rightLeg, ${P} leftLeg) {
        java.util.Map<String, ${P}> children = new java.util.HashMap<>();
        children.put("head", slot(head, ${PP}.ZERO, java.util.Map.of("hat", new ${P}(java.util.List.of(), java.util.Map.of()))));
        children.put("body", slot(body, ${PP}.ZERO, java.util.Map.of()));
        children.put("right_arm", slot(rightArm, ${PP}.offset(-5.0F, 2.0F, 0.0F), java.util.Map.of()));
        children.put("left_arm", slot(leftArm, ${PP}.offset(5.0F, 2.0F, 0.0F), java.util.Map.of()));
        children.put("right_leg", slot(rightLeg, ${PP}.offset(-1.9F, 12.0F, 0.0F), java.util.Map.of()));
        children.put("left_leg", slot(leftLeg, ${PP}.offset(1.9F, 12.0F, 0.0F), java.util.Map.of()));
        return new net.minecraft.client.model.HumanoidModel<>(new ${P}(java.util.List.of(), children));
    }

    private static ${P} slot(${P} part, ${PP} pose, java.util.Map<String, ${P}> extra) {
        java.util.Map<String, ${P}> children = new java.util.HashMap<>(extra);
        if (part != null) {
            part.setInitialPose(${PP}.ZERO);
            part.resetPose();
            children.put("mcedge_part", part);
        }
        ${P} slot = new ${P}(java.util.List.of(), children);
        slot.setInitialPose(pose);
        slot.resetPose();
        return slot;
    }
}
`;
}
