import { idExpr, jfloat, jstr } from "./java.ts";
import { modClassName, registryClassName } from "./registries.ts";
import type { GenEnv, JavaSourceFile } from "./typeModule.ts";

/**
 * Entity types: one generated <Mod><Name> class holding an EntityType field per element, each typed with the
 * element's own entity class (a plain registry class loses that type, which renderer registration needs).
 * Forge 1.16.5 and NeoForge use a DeferredRegister on the mod bus; Fabric registers when the class loads.
 */
export interface EntityTypeEntry {
  /** Field name, "RUBY_ARROW". */
  constant: string;
  /** Registry path, "ruby_arrow". */
  id: string;
  /** Fully qualified entity class with an (EntityType, Level) constructor. */
  entityClass: string;
  /** MobCategory / EntityClassification constant. */
  category: string;
  width: number;
  height: number;
  trackingRange: number;
  updateInterval: number;
  fireImmune?: boolean;
  /** Never written to the world (a seat lives only while someone sits on it). */
  noSave?: boolean;
}

export interface EntityTypeClass {
  source: JavaSourceFile;
  /** Constructor (Forge/NeoForge, `modBus` in scope) or onInitialize (Fabric) statement. */
  init: string;
}

/** Java expression of a registered entity type, typed EntityType<entity class>. */
export function entityTypeValue(env: GenEnv, name: string, constant: string): string {
  const owner = registryClassName(env, name);
  return env.loader === "fabric" ? `${owner}.${constant}` : `${owner}.${constant}.get()`;
}

export function entityTypeClass(env: GenEnv, name: string, entries: EntityTypeEntry[]): EntityTypeClass {
  const pkg = env.project.mod.package;
  const cls = `${modClassName(env)}${name}`;
  const owner = `${pkg}.init.${cls}`;
  const legacy = env.mc === "1.16.5";
  const EntityType = legacy ? "net.minecraft.entity.EntityType" : "net.minecraft.world.entity.EntityType";
  const category = legacy ? "net.minecraft.entity.EntityClassification" : "net.minecraft.world.entity.MobCategory";
  const key = (e: EntityTypeEntry) => `net.minecraft.resources.ResourceKey.create(net.minecraft.core.registries.Registries.ENTITY_TYPE, ${idExpr(env, `${env.modId}:${e.id}`)})`;
  const builder = (e: EntityTypeEntry, built: string) =>
    `${EntityType}.Builder.<${e.entityClass}>of(${e.entityClass}::new, ${category}.${e.category}).sized(${jfloat(e.width)}, ${jfloat(e.height)})${e.fireImmune ? ".fireImmune()" : ""}${e.noSave ? ".noSave()" : ""}.clientTrackingRange(${e.trackingRange}).updateInterval(${e.updateInterval}).build(${built})`;
  let fields: string;
  let init: string;
  if (legacy) {
    fields = `    public static final net.minecraftforge.registries.DeferredRegister<${EntityType}<?>> REGISTRY = net.minecraftforge.registries.DeferredRegister.create(net.minecraftforge.registries.ForgeRegistries.ENTITIES, ${jstr(env.modId)});
${entries.map((e) => `    public static final net.minecraftforge.fml.RegistryObject<${EntityType}<${e.entityClass}>> ${e.constant} = REGISTRY.register(${jstr(e.id)}, () -> ${builder(e, jstr(`${env.modId}:${e.id}`))});`).join("\n")}`;
    init = `${owner}.REGISTRY.register(modBus);`;
  } else if (env.loader === "neoforge") {
    fields = `    public static final net.neoforged.neoforge.registries.DeferredRegister<${EntityType}<?>> REGISTRY = net.neoforged.neoforge.registries.DeferredRegister.create(net.minecraft.core.registries.Registries.ENTITY_TYPE, ${jstr(env.modId)});
${entries.map((e) => `    public static final net.neoforged.neoforge.registries.DeferredHolder<${EntityType}<?>, ${EntityType}<${e.entityClass}>> ${e.constant} = REGISTRY.register(${jstr(e.id)}, () -> ${builder(e, key(e))});`).join("\n")}`;
    init = `${owner}.REGISTRY.register(modBus);`;
  } else {
    fields = `${entries.map((e) => `    public static final ${EntityType}<${e.entityClass}> ${e.constant} = net.minecraft.core.Registry.register(net.minecraft.core.registries.BuiltInRegistries.ENTITY_TYPE, ${key(e)}, ${builder(e, key(e))});`).join("\n")}

    /** Loads the class, which registers its entries. */
    public static void init() {}`;
    init = `${owner}.init();`;
  }
  const code = `package ${pkg}.init;

/** Generated by MCEdge. */
public final class ${cls} {
    private ${cls}() {}

${fields}
}
`;
  return { source: { path: `${pkg.replaceAll(".", "/")}/init/${cls}.java`, code }, init };
}

/**
 * Client statement registering entity renderers. `renderers` pairs an entity type expression with a renderer
 * factory written for the engine (a constructor reference taking the renderer context / manager).
 */
export function rendererRegistration(env: GenEnv, renderers: { type: string; factory: string }[]): string {
  if (!renderers.length) return "";
  if (env.mc === "1.16.5") {
    return `modBus.addListener(net.minecraftforge.eventbus.api.EventPriority.NORMAL, false, net.minecraftforge.fml.event.lifecycle.FMLClientSetupEvent.class, event -> {
${renderers.map((r) => `            net.minecraftforge.fml.client.registry.RenderingRegistry.registerEntityRenderingHandler(${r.type}, ${r.factory});`).join("\n")}
        });`;
  }
  if (env.loader === "neoforge") {
    return `modBus.addListener(net.neoforged.neoforge.client.event.EntityRenderersEvent.RegisterRenderers.class, event -> {
${renderers.map((r) => `            event.registerEntityRenderer(${r.type}, ${r.factory});`).join("\n")}
        });`;
  }
  return renderers.map((r) => `net.fabricmc.fabric.api.client.rendering.v1.EntityRendererRegistry.register(${r.type}, ${r.factory});`).join("\n        ");
}
