/**
 * Special entities are boats and rafts: a Boat or ChestBoat subclass, its item, renderer and a dispenser
 * behaviour. On 1.21.5 and 26.x the renderer uses a model layer with the vanilla boat or raft model and reads the
 * entity texture from textures/entity/(chest_)boat/<id>.png, the path of that layer. 1.16.5 has no boat API for
 * mods: MCEdge generates the boat's item (vanilla BoatItem placement), dispenser behaviour and a BoatRenderer with
 * the element's texture. Chest boats and rafts came with later game versions and are not generated on 1.16.5
 * (layer.json).
 */

const TYPES = "Boats";
const ITEMS = "BoatItems";

const chest = (e: Element) => e.entityType === "ChestBoat" || e.entityType === "ChestRaft";
const raft = (e: Element) => e.entityType === "Raft" || e.entityType === "ChestRaft";
const layerPath = (e: Element) => `${chest(e) ? "chest_boat" : "boat"}/${e.id}`;

function element(entity: Element, env: GenEnv): ElementContext {
  const id = String(entity.id);
  const name = str(entity.name) || id;
  const textures: ElementContext["textures"] = [];
  if (str(entity.entityTexture)) textures.push({ from: str(entity.entityTexture), to: `entity/${layerPath(entity)}` });
  if (str(entity.itemTexture)) textures.push({ from: str(entity.itemTexture), to: `item/${id}` });
  const files: ResourceFile[] = [
    { path: `assets/${env.modId}/models/item/${id}.json`, json: JSON.stringify({ parent: "minecraft:item/generated", textures: { layer0: `${env.modId}:item/${id}` } }, null, 2) },
    { path: `assets/${env.modId}/items/${id}.json`, json: JSON.stringify({ model: { type: "minecraft:model", model: `${env.modId}:item/${id}` } }, null, 2) },
  ];
  return {
    lang: { [`entity.${env.modId}.${id}`]: name, [`item.${env.modId}.${id}`]: name },
    textures,
    files,
    tags: [
      { registry: "item", tag: chest(entity) ? "minecraft:chest_boats" : "minecraft:boats", value: `${env.modId}:${id}` },
      ...(chest(entity) || env.mc === "1.16.5" ? [] : [{ registry: "entity_type", tag: "minecraft:boat", value: `${env.modId}:${id}` }]),
    ],
    tabItems: [registeredValue(env, ITEMS, id.toUpperCase())],
  };
}

function entityClass(env: GenEnv, e: ElementContext): JavaSourceFile {
  if (env.mc === "1.16.5") return legacyEntityClass(env, e);
  const pkg = env.project.mod.package;
  const cls = String(e.className);
  const vehicle = env.mc === "26.3" ? "net.minecraft.world.entity.vehicle.boat" : "net.minecraft.world.entity.vehicle";
  const base = `${vehicle}.${chest(e as unknown as Element) ? "ChestBoat" : "Boat"}`;
  const at = { x: "this.getX()", y: "this.getY()", z: "this.getZ()", world: "this.level()", entity: "this" };
  const onTick = procedureCall(env, "special_entity", e as unknown as Element, "onTickUpdate", at);
  const onTouch = procedureCall(env, "special_entity", e as unknown as Element, "onPlayerCollidesWith", { ...at, sourceentity: "player" });
  const members: string[] = [];
  if (onTick) {
    members.push(`    @Override
    public void baseTick() {
        super.baseTick();
        ${onTick};
    }`);
  }
  if (onTouch) {
    members.push(`    @Override
    public void playerTouch(net.minecraft.world.entity.player.Player player) {
        super.playerTouch(player);
        ${onTouch};
    }`);
  }
  const code = `package ${pkg}.entity;

/** Generated by MCEdge. */
public class ${cls} extends ${base} {
    public ${cls}(net.minecraft.world.entity.EntityType<? extends ${base}> type, net.minecraft.world.level.Level world) {
        super(type, world, () -> ${registeredValue(env, ITEMS, String(e.constant))});
    }
${members.length ? `\n${members.join("\n\n")}\n` : ""}}
`;
  return { path: `${pkg.replaceAll(".", "/")}/entity/${cls}.java`, code };
}

/** 1.16.5: a BoatEntity dropping this element's item, with the item class that places it (vanilla BoatItem logic). */
function legacyEntityClass(env: GenEnv, e: ElementContext): JavaSourceFile {
  const pkg = env.project.mod.package;
  const cls = String(e.className);
  const at = { x: "this.getX()", y: "this.getY()", z: "this.getZ()", world: "this.level", entity: "this" };
  const onTick = procedureCall(env, "special_entity", e as unknown as Element, "onTickUpdate", at);
  const onTouch = procedureCall(env, "special_entity", e as unknown as Element, "onPlayerCollidesWith", { ...at, sourceentity: "player" });
  const members: string[] = [];
  if (onTick) {
    members.push(`    @Override
    public void baseTick() {
        super.baseTick();
        ${onTick};
    }`);
  }
  if (onTouch) {
    members.push(`    @Override
    public void playerTouch(net.minecraft.entity.player.PlayerEntity player) {
        super.playerTouch(player);
        ${onTouch};
    }`);
  }
  const type = entityTypeValue(env, TYPES, String(e.constant));
  const code = `package ${pkg}.entity;

/** Generated by MCEdge. */
public class ${cls} extends net.minecraft.entity.item.BoatEntity {
    public ${cls}(net.minecraft.entity.EntityType<? extends net.minecraft.entity.item.BoatEntity> type, net.minecraft.world.World world) {
        super(type, world);
    }

    @Override
    public net.minecraft.item.Item getDropItem() {
        return ${registeredValue(env, ITEMS, String(e.constant))};
    }

    @Override
    public net.minecraft.network.IPacket<?> getAddEntityPacket() {
        return net.minecraftforge.fml.network.NetworkHooks.getEntitySpawningPacket(this);
    }
${members.length ? `\n${members.join("\n\n")}\n` : ""}
    /** The boat's item: places the boat on the block or water looked at, as vanilla boat items do. */
    public static class BoatItemForm extends net.minecraft.item.Item {
        public BoatItemForm(net.minecraft.item.Item.Properties properties) {
            super(properties);
        }

        @Override
        public net.minecraft.util.ActionResult<net.minecraft.item.ItemStack> use(net.minecraft.world.World world, net.minecraft.entity.player.PlayerEntity player, net.minecraft.util.Hand hand) {
            net.minecraft.item.ItemStack stack = player.getItemInHand(hand);
            net.minecraft.util.math.BlockRayTraceResult hit = getPlayerPOVHitResult(world, player, net.minecraft.util.math.RayTraceContext.FluidMode.ANY);
            if (hit.getType() != net.minecraft.util.math.RayTraceResult.Type.BLOCK) return net.minecraft.util.ActionResult.pass(stack);
            net.minecraft.util.math.vector.Vector3d view = player.getViewVector(1.0F);
            net.minecraft.util.math.vector.Vector3d eye = player.getEyePosition(1.0F);
            for (net.minecraft.entity.Entity entity : world.getEntities(player, player.getBoundingBox().expandTowards(view.scale(5.0)).inflate(1.0), net.minecraft.util.EntityPredicates.NO_SPECTATORS.and(net.minecraft.entity.Entity::isPickable))) {
                if (entity.getBoundingBox().inflate(entity.getPickRadius()).contains(eye)) return net.minecraft.util.ActionResult.pass(stack);
            }
            ${cls} boat = new ${cls}(${type}, world);
            boat.setPos(hit.getLocation().x, hit.getLocation().y, hit.getLocation().z);
            boat.yRot = player.yRot;
            if (!world.noCollision(boat, boat.getBoundingBox().inflate(-0.1))) return net.minecraft.util.ActionResult.fail(stack);
            if (!world.isClientSide()) {
                world.addFreshEntity(boat);
                if (!player.abilities.instabuild) stack.shrink(1);
            }
            player.awardStat(net.minecraft.stats.Stats.ITEM_USED.get(this));
            return net.minecraft.util.ActionResult.sidedSuccess(stack, world.isClientSide());
        }
    }
}
`;
  return { path: `${pkg.replaceAll(".", "/")}/entity/${cls}.java`, code };
}

/** 1.16.5: a BoatRenderer drawing the vanilla boat model with this element's texture. */
function legacyRenderer(env: GenEnv, e: ElementContext): JavaSourceFile {
  const pkg = env.project.mod.package;
  const cls = `${e.className}Renderer`;
  const code = `package ${pkg}.client;

/** Generated by MCEdge. */
public class ${cls} extends net.minecraft.client.renderer.entity.BoatRenderer {
    private static final net.minecraft.util.ResourceLocation TEXTURE = new net.minecraft.util.ResourceLocation(${jstr(env.modId)}, ${jstr(`textures/entity/${layerPath(e as unknown as Element)}.png`)});

    public ${cls}(net.minecraft.client.renderer.entity.EntityRendererManager manager) {
        super(manager);
    }

    @Override
    public net.minecraft.util.ResourceLocation getTextureLocation(net.minecraft.entity.item.BoatEntity boat) {
        return TEXTURE;
    }
}
`;
  return { path: `${pkg.replaceAll(".", "/")}/client/${cls}.java`, code };
}

/** 1.16.5 boat dispensing (vanilla's behaviour is private): on water, or in air above water. */
function legacyDispense(env: GenEnv, e: ElementContext): string {
  const cls = `${env.project.mod.package}.entity.${e.className}`;
  return `net.minecraft.block.DispenserBlock.registerBehavior(${registeredValue(env, ITEMS, String(e.constant))}, new net.minecraft.dispenser.DefaultDispenseItemBehavior() {
                @Override
                protected net.minecraft.item.ItemStack execute(net.minecraft.dispenser.IBlockSource source, net.minecraft.item.ItemStack stack) {
                    net.minecraft.util.Direction facing = source.getBlockState().getValue(net.minecraft.block.DispenserBlock.FACING);
                    net.minecraft.world.World world = source.getLevel();
                    net.minecraft.util.math.BlockPos front = source.getPos().relative(facing);
                    double lift;
                    if (world.getFluidState(front).is(net.minecraft.tags.FluidTags.WATER)) {
                        lift = 1.0;
                    } else if (world.isEmptyBlock(front) && world.getFluidState(front.below()).is(net.minecraft.tags.FluidTags.WATER)) {
                        lift = 0.0;
                    } else {
                        return new net.minecraft.dispenser.DefaultDispenseItemBehavior().dispense(source, stack);
                    }
                    ${cls} boat = new ${cls}(${entityTypeValue(env, TYPES, String(e.constant))}, world);
                    boat.setPos(source.x() + facing.getStepX() * 1.125, source.y() + facing.getStepY() * 1.125 + lift, source.z() + facing.getStepZ() * 1.125);
                    boat.yRot = facing.toYRot();
                    world.addFreshEntity(boat);
                    stack.shrink(1);
                    return stack;
                }
            });`;
}

function clientRegistration(env: GenEnv, entities: ElementContext[]): string[] {
  if (env.mc === "1.16.5") {
    return [rendererRegistration(env, entities.map((e) => ({ type: entityTypeValue(env, TYPES, String(e.constant)), factory: `${env.project.mod.package}.client.${e.className}Renderer::new` })))];
  }
  const models = env.mc === "26.3" ? "net.minecraft.client.model.object.boat" : "net.minecraft.client.model";
  const layer = (e: Element) => `new net.minecraft.client.model.geom.ModelLayerLocation(${idExpr(env, `${env.modId}:${layerPath(e)}`)}, "main")`;
  const definition = (e: Element) => `${models}.${raft(e) ? "RaftModel" : "BoatModel"}::create${e.entityType}Model`;
  const layers = entities.map((ctx) => ctx as unknown as Element).map((e) => ({ layer: layer(e), definition: definition(e) }));
  const renderers = entities.map((ctx) => {
    const e = ctx as unknown as Element;
    const renderer = `net.minecraft.client.renderer.entity.${raft(e) ? "RaftRenderer" : "BoatRenderer"}`;
    return { type: entityTypeValue(env, TYPES, String(ctx.constant)), factory: `context -> new ${renderer}(context, ${layer(e)})` };
  });
  const layerCode = env.loader === "neoforge"
    ? `modBus.addListener(net.neoforged.neoforge.client.event.EntityRenderersEvent.RegisterLayerDefinitions.class, event -> {
${layers.map((l) => `            event.registerLayerDefinition(${l.layer}, ${l.definition});`).join("\n")}
        });`
    : layers.map((l) => `net.fabricmc.fabric.api.client.rendering.v1.${env.mc === "26.3" ? "ModelLayerRegistry" : "EntityModelLayerRegistry"}.registerModelLayer(${l.layer}, ${l.definition});`).join("\n        ");
  return [layerCode, rendererRegistration(env, renderers)];
}

export default {
  element,
  runtime(entities, env) {
    if (!entities.length) return {};
    const pkg = env.project.mod.package;
    const types = entityTypeClass(env, TYPES, entities.map((e) => ({
      constant: String(e.constant),
      id: String(e.id),
      entityClass: `${pkg}.entity.${e.className}`,
      category: "MISC",
      width: 1.375,
      height: 0.5625,
      trackingRange: 10,
      updateInterval: 3,
    })));
    const legacy = env.mc === "1.16.5";
    const items = registryClass(env, {
      name: ITEMS,
      valueType: legacy ? "net.minecraft.item.Item" : "net.minecraft.world.item.Item",
      forge: "net.minecraftforge.registries.ForgeRegistries.ITEMS",
      key: "ITEM",
      entries: entities.map((e) => ({
        constant: String(e.constant),
        id: String(e.id),
        factory: legacy
          ? `new ${pkg}.entity.${e.className}.BoatItemForm(new net.minecraft.item.Item.Properties().stacksTo(1).rarity(net.minecraft.item.Rarity.${str(e.rarity) || "COMMON"})${vanillaTab1165(env, e.creativeTabs) ? `.tab(${vanillaTab1165(env, e.creativeTabs)})` : ""})`
          : `new net.minecraft.world.item.BoatItem(${entityTypeValue(env, TYPES, String(e.constant))}, new net.minecraft.world.item.Item.Properties().setId(net.minecraft.resources.ResourceKey.create(net.minecraft.core.registries.Registries.ITEM, ${idExpr(env, `${env.modId}:${e.id}`)})).stacksTo(1).rarity(net.minecraft.world.item.Rarity.${str(e.rarity) || "COMMON"}))`,
      })),
    });
    const dispense = legacy ? entities.map((e) => legacyDispense(env, e)) : entities.map((e) => `net.minecraft.world.level.block.DispenserBlock.registerBehavior(${registeredValue(env, ITEMS, String(e.constant))}, new net.minecraft.core.dispenser.BoatDispenseItemBehavior(${entityTypeValue(env, TYPES, String(e.constant))}));`);
    const setupEvent = legacy
      ? "net.minecraftforge.eventbus.api.EventPriority.NORMAL, false, net.minecraftforge.fml.event.lifecycle.FMLCommonSetupEvent.class"
      : "net.neoforged.fml.event.lifecycle.FMLCommonSetupEvent.class";
    const dispenseInit = env.loader !== "fabric"
      ? `modBus.addListener(${setupEvent}, event -> event.enqueueWork(() -> {
${dispense.map((d) => `            ${d}`).join("\n")}
        }));`
      : dispense.join("\n        ");
    return {
      sources: [types.source, items.source, ...entities.map((e) => entityClass(env, e)), ...(legacy ? entities.map((e) => legacyRenderer(env, e)) : [])],
      init: [types.init, items.init, dispenseInit],
      clientInit: clientRegistration(env, entities),
    };
  },
} satisfies TypeModule;
