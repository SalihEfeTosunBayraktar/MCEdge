import type { Element } from "../../elements/model.ts";
import { str } from "../java.ts";
import { modClassName } from "../registries.ts";
import type { ElementContext, GenEnv, TypeModule } from "../typeModule.ts";

/**
 * Damage types: a damage_type registry file on 1.21.5+; on 1.16.5, which has no such registry, a DamageSource
 * constant in <Mod>DamageTypes. The message id is "<modid>.<id>" so death messages do not clash between mods.
 */

/** "<player>", "<attacker>" and "<item>" in death messages become the translation arguments. */
const message = (text: unknown) => str(text).replaceAll("<player>", "%1$s").replaceAll("<attacker>", "%2$s").replaceAll("<item>", "%3$s");

function element(type: Element, env: GenEnv): ElementContext {
  const messageId = `${env.modId}.${type.id}`;
  const lang = {
    [`death.attack.${messageId}`]: message(type.normalDeathMessage),
    [`death.attack.${messageId}.item`]: message(type.itemDeathMessage),
    [`death.attack.${messageId}.player`]: message(type.playerDeathMessage),
  };
  if (env.mc === "1.16.5") return { lang, messageId };
  const json = {
    exhaustion: Number(type.exhaustion),
    message_id: messageId,
    scaling: str(type.scaling),
    ...(type.effects !== "hurt" ? { effects: str(type.effects) } : {}),
  };
  return { lang, files: [{ path: `data/${env.modId}/damage_type/${type.id}.json`, json: JSON.stringify(json, null, 2) }] };
}

export default {
  element,
  runtime: (contexts: ElementContext[], env: GenEnv) => {
    if (env.mc !== "1.16.5" || !contexts.length) return {};
    const pkg = env.project.mod.package;
    const cls = `${modClassName(env)}DamageTypes`;
    const fields = contexts.map((ctx) => `    public static final net.minecraft.util.DamageSource ${ctx.constant} = new net.minecraft.util.DamageSource(${JSON.stringify(ctx.messageId)})${ctx.scaling === "always" ? ".setScalesWithDifficulty()" : ""};`);
    const code = `package ${pkg}.init;

/** Generated by MCEdge. Damage sources of this mod. */
public final class ${cls} {
    private ${cls}() {}

${fields.join("\n")}
}
`;
    return { sources: [{ path: `${pkg.replaceAll(".", "/")}/init/${cls}.java`, code }] };
  },
} satisfies TypeModule;
