import type { Element } from "../../elements/model.ts";
import { str } from "../java.ts";
import { modClassName, registryClass } from "../registries.ts";
import type { ElementContext, GenEnv, TypeModule } from "../typeModule.ts";

/**
 * Game rules: number or logic rules in <Mod>GameRules. Before 26.x a rule is a key registered by its camelCase name
 * ("ruby_rule" -> /gamerule rubyRule), as procedure blocks look rules up by that name; 26.x has a game rule registry
 * with namespaced ids.
 */

const camel = (id: string) => id.replace(/_([a-z0-9])/g, (_, c: string) => c.toUpperCase());
/** The name /gamerule uses before 26.x: the element's `ruleName`, else the camelCase of its id. */
const gameName = (rule: Record<string, unknown>) => str(rule.ruleName) || camel(String(rule.id));

function element(rule: Element, env: GenEnv): ElementContext {
  const key = env.mc === "26.3" ? `gamerule.${env.modId}.${rule.id}` : `gamerule.${gameName(rule)}`;
  return { lang: { [key]: str(rule.displayName), [`${key}.description`]: str(rule.description) } };
}

/** 1.16.5 keeps the rule type factories private; they are called by their SRG names (remapped in dev). */
const LEGACY_FACTORIES = (G: string) => ["IntegerValue:intRule:int:func_223559_b", "BooleanValue:booleanRule:boolean:func_223568_b"].map((spec) => {
  const [value, name, param, srg] = spec.split(":");
  return `
    @SuppressWarnings("unchecked")
    private static ${G}.RuleType<${G}.${value}> ${name}(${param} value) {
        try {
            return (${G}.RuleType<${G}.${value}>) net.minecraftforge.fml.common.ObfuscationReflectionHelper.findMethod(${G}.${value}.class, "${srg}", ${param}.class).invoke(null, value);
        } catch (ReflectiveOperationException e) {
            throw new IllegalStateException(e);
        }
    }
`;
}).join("");

function value(rule: ElementContext): string {
  return rule.type === "Number" ? String(Number(rule.defaultValueNumber)) : String(rule.defaultValueLogic === true);
}

export default {
  element,
  runtime: (contexts: ElementContext[], env: GenEnv) => {
    if (!contexts.length) return {};
    const pkg = env.project.mod.package;
    if (env.mc === "26.3") {
      const g = "net.minecraft.world.level.gamerules";
      const reg = registryClass(env, {
        name: "GameRules",
        valueType: `${g}.GameRule<?>`,
        key: "GAME_RULE",
        entries: contexts.map((rule) => ({
          constant: String(rule.constant),
          id: String(rule.id),
          factory: rule.type === "Number"
            ? `new ${g}.GameRule<Integer>(${g}.GameRuleCategory.${str(rule.category)}, ${g}.GameRuleType.INT, com.mojang.brigadier.arguments.IntegerArgumentType.integer(), ${g}.GameRuleTypeVisitor::visitInteger, com.mojang.serialization.Codec.INT, i -> i, ${value(rule)}, net.minecraft.world.flag.FeatureFlagSet.of())`
            : `new ${g}.GameRule<Boolean>(${g}.GameRuleCategory.${str(rule.category)}, ${g}.GameRuleType.BOOL, com.mojang.brigadier.arguments.BoolArgumentType.bool(), ${g}.GameRuleTypeVisitor::visitBoolean, com.mojang.serialization.Codec.BOOL, b -> b ? 1 : 0, ${value(rule)}, net.minecraft.world.flag.FeatureFlagSet.of())`,
        })),
      });
      return { sources: [reg.source], init: [reg.init] };
    }
    const legacy = env.mc === "1.16.5";
    const G = legacy ? "net.minecraft.world.GameRules" : "net.minecraft.world.level.GameRules";
    const keyType = legacy ? "RuleKey" : "Key";
    const fabric = env.loader === "fabric";
    const fields = contexts.map((rule) => {
      const number = rule.type === "Number";
      const valueType = `${G}.${number ? "IntegerValue" : "BooleanValue"}`;
      const type = fabric
        ? `net.fabricmc.fabric.api.gamerule.v1.GameRuleFactory.${number ? "createIntRule" : "createBooleanRule"}(${value(rule)})`
        : legacy ? `${number ? "intRule" : "booleanRule"}(${value(rule)})` : `${valueType}.create(${value(rule)})`;
      const register = fabric ? "net.fabricmc.fabric.api.gamerule.v1.GameRuleRegistry.register" : `${G}.register`;
      return `    public static final ${G}.${keyType}<${valueType}> ${rule.constant} = ${register}(${JSON.stringify(gameName(rule))}, ${G}.Category.${str(rule.category)}, ${type});`;
    });
    const cls = `${modClassName(env)}GameRules`;
    const code = `package ${pkg}.init;

/** Generated by MCEdge. Game rules of this mod, registered when the class loads. */
public final class ${cls} {
    private ${cls}() {}

${fields.join("\n")}

    public static void init() {}
${legacy ? LEGACY_FACTORIES(G) : ""}}
`;
    return { sources: [{ path: `${pkg.replaceAll(".", "/")}/init/${cls}.java`, code }], init: [`${pkg}.init.${cls}.init();`] };
  },
} satisfies TypeModule;
