/**
 * Animated GUI textures (Q229): one small runtime, <Mod>TextureAnimations, with the frame rule of every playback mode
 * (data: the frame order and times of each texture, from the shared model in src/resources/textureAnimation.ts) and the
 * start times the "restart GUI image animation" procedure block sets. Blocks and items need none of it: their
 * playback mode is written into the vanilla .mcmeta (vanillaMcmeta).
 */

export const textureAnimationsClass = (env: GenEnv) => `${env.project.mod.package}.client.${modClassName(env)}TextureAnimations`;

/**
 * Java int expression of the strip frame shown `clock` (a long, milliseconds since the start) into `schedule`. A plain
 * loop through the frames in order is the old arithmetic; frame lists, own times and once modes ask the runtime.
 */
export function frameIndexExpr(env: GenEnv, schedule: AnimationSchedule, clock: string): string {
  const { frames } = schedule;
  const time = frames[0].time;
  if (schedule.hold === undefined && frames.every((f, i) => f.index === i && f.time === time)) return `((${clock} / ${time * 50}L) % ${frames.length}L)`;
  return `${textureAnimationsClass(env)}.frame(${clock}, new int[] {${frames.map((f) => f.index).join(", ")}}, new int[] {${frames.map((f) => f.time).join(", ")}}, ${schedule.hold ?? -1})`;
}

/** Key of a GUI image for restart and since: its name, else its number in the GUI. */
export const imageKey = (name: unknown, index: number) => (typeof name === "string" && name ? name : String(index));

export function textureAnimationsSource(env: GenEnv): JavaSourceFile {
  const cls = textureAnimationsClass(env);
  const pkg = cls.slice(0, cls.lastIndexOf("."));
  const simple = cls.slice(cls.lastIndexOf(".") + 1);
  const code = `package ${pkg};

/**
 * Generated by MCEdge (Q229): which frame of an animated GUI texture shows, for every playback mode, and when the GUI
 * images started by a procedure ("restart GUI image animation") last started.
 */
public final class ${simple} {
    private static final java.util.Map<String, Long> STARTS = new java.util.concurrent.ConcurrentHashMap<>();

    private ${simple}() {}

    /** Starts the procedure-started images of a GUI again: the one named \`image\`, or all of them when it is empty. */
    public static void restart(String gui, String image) {
        STARTS.put(gui + "/" + (image == null ? "" : image), System.currentTimeMillis());
    }

    /** Milliseconds since the image (or its whole GUI) last started; -1 before the first start. */
    public static long since(String gui, String image) {
        long start = Math.max(STARTS.getOrDefault(gui + "/", -1L), STARTS.getOrDefault(gui + "/" + image, -1L));
        return start < 0L ? -1L : System.currentTimeMillis() - start;
    }

    /**
     * The strip frame shown \`ms\` after the start: frames[i] for ticks[i] ticks (50 ms) each; with hold >= 0 that frame
     * stays after one pass, else the frames loop. Before the start (ms < 0) the first frame shows.
     */
    public static int frame(long ms, int[] frames, int[] ticks, int hold) {
        long total = 0L;
        for (int t : ticks) total += t;
        long t = Math.max(0L, ms) / 50L;
        if (hold >= 0 && t >= total) return hold;
        t %= total;
        for (int i = 0; i < frames.length; i++) {
            if (t < ticks[i]) return frames[i];
            t -= ticks[i];
        }
        return frames[frames.length - 1];
    }
}
`;
  return { path: `${cls.replaceAll(".", "/")}.java`, code };
}

/** Whether a project texture plays once (hold_last, hold_first): then block and item sprites restart at world join. */
function hasOnceTextures(projectDir: string): boolean {
  const walk = (dir: string): boolean => {
    if (!existsSync(dir)) return false;
    return readdirSync(dir, { withFileTypes: true }).some((e) => {
      const path = join(dir, e.name);
      if (e.isDirectory()) return walk(path);
      if (!e.name.endsWith(".png.mcmeta")) return false;
      try {
        const mode = playbackModeOf(JSON.parse(readFileSync(path, "utf8")));
        return mode === "hold_last" || mode === "hold_first";
      } catch {
        return false;
      }
    });
  };
  return walk(join(projectDir, "textures"));
}

/**
 * Block and item textures that play once (Q229): the game starts every atlas animation when it loads the textures, so
 * by the time a world shows, a short one has long ended. <Mod>SpriteAnimations starts the mod's animated block and item
 * sprites again on the first client tick in the world after joining it (loading screen gone), so "once" means once per
 * world join (and once per resource reload, F3+T). The atlas keeps its animations private, so they are found by type,
 * not name (names differ per mapping): the list of animated entries, each entry's sprite, and its counters (the frame
 * and the tick in it), the only non-final int fields; setting both to 0 starts it again.
 */
export function spriteAnimationOutputs(env: GenEnv): { sources: JavaSourceFile[]; clientInit: string[] } {
  if (!hasOnceTextures(env.projectDir)) return { sources: [], clientInit: [] };
  const pkg = `${env.project.mod.package}.client`;
  const cls = `${modClassName(env)}SpriteAnimations`;
  const mc = "net.minecraft.client.Minecraft";
  const T = "net.minecraft.client.renderer.texture";
  const modId = JSON.stringify(env.modId);
  let atlases: string, atlasType: string, perEntry: string;
  if (env.mc === "1.16.5") {
    atlases = `${T}.AtlasTexture.LOCATION_BLOCKS`;
    atlasType = `${T}.AtlasTexture`;
    perEntry = `if (!(entry instanceof ${T}.TextureAtlasSprite)) continue;
                        ${T}.TextureAtlasSprite sprite = (${T}.TextureAtlasSprite) entry;
                        if (!${modId}.equals(sprite.getName().getNamespace())) continue;
                        zero(sprite, ${T}.TextureAtlasSprite.class);
                        atlas.bind();
                        sprite.uploadFirstFrame();`;
  } else if (env.mc === "1.21.5") {
    atlases = `${T}.TextureAtlas.LOCATION_BLOCKS`;
    atlasType = `${T}.TextureAtlas`;
    perEntry = `if (!(entry instanceof ${T}.TextureAtlasSprite.Ticker)) continue;
                        ${T}.TextureAtlasSprite sprite = null;
                        Object ticker = null;
                        for (java.lang.reflect.Field field : entry.getClass().getDeclaredFields()) {
                            if (field.getType().isPrimitive() || java.lang.reflect.Modifier.isStatic(field.getModifiers())) continue;
                            field.setAccessible(true);
                            Object value = field.get(entry);
                            if (value instanceof ${T}.TextureAtlasSprite) sprite = (${T}.TextureAtlasSprite) value;
                            else if (value instanceof ${T}.SpriteTicker) ticker = value;
                        }
                        if (sprite == null || ticker == null || !${modId}.equals(sprite.contents().name().getNamespace())) continue;
                        zero(ticker, ticker.getClass());
                        sprite.uploadFirstFrame(atlas.getTexture());`;
  } else {
    atlases = `${T}.TextureAtlas.LOCATION_BLOCKS, ${T}.TextureAtlas.LOCATION_ITEMS`;
    atlasType = `${T}.TextureAtlas`;
    perEntry = `if (!(entry instanceof ${T}.SpriteContents.AnimationState)) continue;
                        ${T}.SpriteContents contents = null;
                        for (java.lang.reflect.Field field : entry.getClass().getDeclaredFields()) {
                            if (field.getType().isPrimitive() || java.lang.reflect.Modifier.isStatic(field.getModifiers())) continue;
                            field.setAccessible(true);
                            Object value = field.get(entry);
                            if (value == null) continue;
                            for (java.lang.reflect.Field inner : value.getClass().getDeclaredFields()) {
                                if (inner.getType() != ${T}.SpriteContents.class) continue;
                                inner.setAccessible(true);
                                contents = (${T}.SpriteContents) inner.get(value);
                            }
                        }
                        if (contents == null || !${modId}.equals(contents.name().getNamespace())) continue;
                        zero(entry, entry.getClass());`;
  }
  const Id = env.mc === "1.16.5" ? "net.minecraft.util.ResourceLocation" : env.mc === "26.3" ? "net.minecraft.resources.Identifier" : "net.minecraft.resources.ResourceLocation";
  const listen = env.loader === "fabric"
    ? `net.fabricmc.fabric.api.client.networking.v1.ClientPlayConnectionEvents.JOIN.register((handler, sender, client) -> pending = true);
        net.fabricmc.fabric.api.client.event.lifecycle.v1.ClientTickEvents.END_CLIENT_TICK.register(client -> tick());`
    : env.loader === "neoforge"
      ? `net.neoforged.neoforge.common.NeoForge.EVENT_BUS.addListener(net.neoforged.neoforge.client.event.ClientPlayerNetworkEvent.LoggingIn.class, event -> pending = true);
        net.neoforged.neoforge.common.NeoForge.EVENT_BUS.addListener(net.neoforged.neoforge.client.event.ClientTickEvent.Post.class, event -> tick());`
      : `net.minecraftforge.common.MinecraftForge.EVENT_BUS.addListener(net.minecraftforge.eventbus.api.EventPriority.NORMAL, false, net.minecraftforge.client.event.ClientPlayerNetworkEvent.LoggedInEvent.class, event -> pending = true);
        net.minecraftforge.common.MinecraftForge.EVENT_BUS.addListener(net.minecraftforge.eventbus.api.EventPriority.NORMAL, false, net.minecraftforge.event.TickEvent.ClientTickEvent.class, event -> {
            if (event.phase == net.minecraftforge.event.TickEvent.Phase.END) tick();
        });`;
  const code = `package ${pkg};

/**
 * Generated by MCEdge (Q229): the mod's animated block and item textures start again when the player is in a world
 * after joining it, so a texture that plays once (and holds a frame) plays where it is seen. Runs once per join.
 */
public final class ${cls} {
    private static boolean pending;

    private ${cls}() {}

    public static void register() {
        ${listen}
    }

    private static void tick() {
        ${mc} mc = ${mc}.getInstance();
        if (!pending || mc.player == null || ${env.mc === "26.3" ? "mc.gui.screen()" : "mc.screen"} != null) return;
        pending = false;
        restart();
    }

    /** Starts every animated sprite of the mod in the block and item atlases from its first frame. */
    public static void restart() {
        for (${Id} id : new ${Id}[] {${atlases}}) {
            try {
                Object texture = ${mc}.getInstance().getTextureManager().getTexture(id);
                if (!(texture instanceof ${atlasType})) continue;
                ${atlasType} atlas = (${atlasType}) texture;
                for (java.lang.reflect.Field list : ${atlasType}.class.getDeclaredFields()) {
                    if (!java.util.List.class.isAssignableFrom(list.getType())) continue;
                    list.setAccessible(true);
                    Object entries = list.get(atlas);
                    if (entries == null) continue;
                    for (Object entry : (java.util.List<?>) entries) {
                        ${perEntry}
                    }
                }
            } catch (ReflectiveOperationException | RuntimeException e) {
                // A layout this code does not know leaves the animations as the game plays them.
            }
        }
    }

    /** Sets the non-final int fields of \`owner\` (an animation's frame and tick counters) to 0 and its flags to true (redraw). */
    private static void zero(Object owner, Class<?> type) throws IllegalAccessException {
        for (java.lang.reflect.Field field : type.getDeclaredFields()) {
            int mods = field.getModifiers();
            if (java.lang.reflect.Modifier.isStatic(mods) || java.lang.reflect.Modifier.isFinal(mods)) continue;
            if (field.getType() == int.class) {
                field.setAccessible(true);
                field.setInt(owner, 0);
            } else if (field.getType() == boolean.class) {
                field.setAccessible(true);
                field.setBoolean(owner, true);
            }
        }
    }
}
`;
  return { sources: [{ path: `${pkg.replaceAll(".", "/")}/${cls}.java`, code }], clientInit: [`${pkg}.${cls}.register();`] };
}
