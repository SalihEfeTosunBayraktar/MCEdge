/**
 * Session GUIs (Q205): a GUI with `inventorySource: "session"` takes its slots from a shared server-side inventory
 * named by a text id instead of a block entity, so several players opening the same id share one window with no
 * block. <Mod>GuiSessions keeps those inventories with their values (text, number, logic) and viewers; the last
 * viewer closing drops the session and gives every item left to the player who last added to its slot (when online),
 * else to that viewer. The client keeps the id and values of the session its open menu shows (sent by the menu).
 */

export const isSessionGui = (gui: Element | Record<string, unknown>) => gui.inventorySource === "session";

/** Session GUIs of the project. */
export const sessionGuis = (env: GenEnv): Element[] => (env.generated.gui ?? []).filter(isSessionGui);

/** Slots a session of `gui` has: its `inventorySize`, at least one past its highest slot id. */
export function sessionSize(gui: Element, slots: number): number {
  const size = Math.round(Number(gui.inventorySize));
  return Math.max(1, slots, Number.isFinite(size) && gui.inventorySize !== "" ? Math.min(size, 256) : 0);
}

