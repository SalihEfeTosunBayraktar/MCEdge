import type { Element } from "../../elements/model.ts";
import { itemExpr, jstr, list, pascal, str } from "../java.ts";
import { modClassName } from "../registries.ts";
import type { GenEnv, JavaSourceFile } from "../typeModule.ts";

/**
 * Recipe viewer integration (KUYRUK 101, config/integrations/recipe_viewer.json): every block with `rvCategory` is a
 * machine with its own recipe category in JEI (Forge 1.16.5: JEI 7; NeoForge 1.21.5 / 26.3: JEI 21 / 31) or REI
 * (Fabric 1.21.5 / 26.3), the block and `rvCatalysts` as its crafting stations, `rvRecipes` as its recipes: inputs, an
 * arrow, outputs, and the time and energy under them. The plugin is found by JEI's @JeiPlugin annotation or REI's
 * rei_client entrypoint, so the mod runs without the other mod installed.
 */
interface Stack {
  item: string;
  count: number;
}
interface Machine {
  id: string;
  title: string;
  icon: string;
  catalysts: string[];
  recipes: { inputs: Stack[]; outputs: Stack[]; time: number; energy: number }[];
  inputs: number;
  outputs: number;
}

const SLOT = 18;
const ARROW = 28;

function machines(env: GenEnv): Machine[] {
  const stacks = (rows: unknown): Stack[] =>
    list<Record<string, unknown>>(rows).filter((r) => str(r.item)).map((r) => ({ item: str(r.item), count: Math.max(1, Math.min(64, Math.round(Number(r.count) || 1))) }));
  return (env.generated.block ?? []).filter((b: Element) => b.rvCategory === true).map((b: Element) => {
    const recipes = list<Record<string, unknown>>(b.rvRecipes).map((r) => ({
      inputs: stacks(r.inputs), outputs: stacks(r.outputs), time: Math.max(0, Math.round(Number(r.time) || 0)), energy: Math.max(0, Math.round(Number(r.energy) || 0)),
    })).filter((r) => r.inputs.length || r.outputs.length);
    return {
      id: b.id,
      title: str(b.rvTitle) || str(b.name) || b.id,
      icon: b.id,
      catalysts: list<Record<string, unknown>>(b.rvCatalysts).map((c) => str(c.item)).filter(Boolean),
      recipes,
      inputs: Math.max(1, ...recipes.map((r) => r.inputs.length)),
      outputs: Math.max(1, ...recipes.map((r) => r.outputs.length)),
    };
  });
}

/** Java sources and Fabric entrypoints of the integration on this engine; nothing without a machine. */
export function recipeViewerOutputs(env: GenEnv): { sources: JavaSourceFile[]; entrypoints: { name: string; classes: string }[] } {
  const all = machines(env);
  if (!all.length) return { sources: [], entrypoints: [] };
  const pkg = `${env.project.mod.package}.integration`;
  const dir = pkg.replaceAll(".", "/");
  const legacy = env.mc === "1.16.5";
  const Stack = legacy ? "net.minecraft.item.ItemStack" : "net.minecraft.world.item.ItemStack";
  const recipeClass = `${modClassName(env)}MachineRecipe`;
  const stack = (s: Stack) => `new ${Stack}(${itemExpr(env, s.item)}, ${s.count})`;
  const recipeSource: JavaSourceFile = {
    path: `${dir}/${recipeClass}.java`,
    code: `package ${pkg};

/** Generated by MCEdge: one recipe of a machine shown in the recipe viewer. */
public class ${recipeClass} {
    public final java.util.List<${Stack}> inputs;
    public final java.util.List<${Stack}> outputs;
    public final int time;
    public final int energy;

    public ${recipeClass}(java.util.List<${Stack}> inputs, java.util.List<${Stack}> outputs, int time, int energy) {
        this.inputs = inputs;
        this.outputs = outputs;
        this.time = time;
        this.energy = energy;
    }

    /** "5.0 s, 200 FE": what the recipe takes, or empty. */
    public String info() {
        String text = this.time > 0 ? (this.time / 20.0) + " s" : "";
        if (this.energy > 0) text += (text.isEmpty() ? "" : ", ") + this.energy + " FE";
        return text;
    }
}
`,
  };
  const recipesOf = (m: Machine) => m.recipes.map((r) =>
    `new ${recipeClass}(java.util.Arrays.asList(${r.inputs.map(stack).join(", ")}), java.util.Arrays.asList(${r.outputs.map(stack).join(", ")}), ${r.time}, ${r.energy})`);
  const width = (m: Machine) => m.inputs * SLOT + ARROW + m.outputs * SLOT;
  const height = (m: Machine) => SLOT + (m.recipes.some((r) => r.time || r.energy) ? 12 : 0);
  const outX = (m: Machine) => m.inputs * SLOT + ARROW;
  const cls = `${modClassName(env)}${env.loader === "fabric" ? "Rei" : "Jei"}Plugin`;
  const sources = [recipeSource];

  if (env.loader !== "fabric" && legacy) {
    // JEI 7 (1.16.5): categories by ResourceLocation uid, ingredients set before the layout.
    const uid = (m: Machine) => `new net.minecraft.util.ResourceLocation(${jstr(env.modId)}, ${jstr(m.id)})`;
    const categories = all.map((m) => `
    public static class ${pascal(m.id)}Category implements mezz.jei.api.recipe.category.IRecipeCategory<${recipeClass}> {
        private final mezz.jei.api.gui.drawable.IDrawable background;
        private final mezz.jei.api.gui.drawable.IDrawable icon;

        public ${pascal(m.id)}Category(mezz.jei.api.helpers.IGuiHelper guiHelper) {
            this.background = guiHelper.createBlankDrawable(${width(m)}, ${height(m)});
            this.icon = guiHelper.createDrawableIngredient(new ${Stack}(${itemExpr(env, m.icon)}));
        }

        @Override public net.minecraft.util.ResourceLocation getUid() { return ${uid(m)}; }
        @Override public Class<? extends ${recipeClass}> getRecipeClass() { return ${recipeClass}.class; }
        @Override public String getTitle() { return ${jstr(m.title)}; }
        @Override public mezz.jei.api.gui.drawable.IDrawable getBackground() { return this.background; }
        @Override public mezz.jei.api.gui.drawable.IDrawable getIcon() { return this.icon; }

        @Override
        public void setIngredients(${recipeClass} recipe, mezz.jei.api.ingredients.IIngredients ingredients) {
            ingredients.setInputs(mezz.jei.api.constants.VanillaTypes.ITEM, recipe.inputs);
            ingredients.setOutputs(mezz.jei.api.constants.VanillaTypes.ITEM, recipe.outputs);
        }

        @Override
        public void setRecipe(mezz.jei.api.gui.IRecipeLayout layout, ${recipeClass} recipe, mezz.jei.api.ingredients.IIngredients ingredients) {
            mezz.jei.api.gui.ingredient.IGuiItemStackGroup stacks = layout.getItemStacks();
            for (int i = 0; i < recipe.inputs.size(); i++) {
                stacks.init(i, true, i * ${SLOT}, 0);
                stacks.set(i, recipe.inputs.get(i));
            }
            for (int i = 0; i < recipe.outputs.size(); i++) {
                stacks.init(100 + i, false, ${outX(m)} + i * ${SLOT}, 0);
                stacks.set(100 + i, recipe.outputs.get(i));
            }
        }

        @Override
        public void draw(${recipeClass} recipe, com.mojang.blaze3d.matrix.MatrixStack matrix, double mouseX, double mouseY) {
            net.minecraft.client.Minecraft mc = net.minecraft.client.Minecraft.getInstance();
            mc.font.draw(matrix, "->", ${m.inputs * SLOT + 8}, 5, 0xFF404040);
            if (!recipe.info().isEmpty()) mc.font.draw(matrix, recipe.info(), 0, ${SLOT + 2}, 0xFF404040);
        }
    }`).join("\n");
    sources.push({
      path: `${dir}/${cls}.java`,
      code: `package ${pkg};

/** Generated by MCEdge: JEI plugin with a recipe category per machine block. */
@mezz.jei.api.JeiPlugin
public class ${cls} implements mezz.jei.api.IModPlugin {
    @Override
    public net.minecraft.util.ResourceLocation getPluginUid() {
        return new net.minecraft.util.ResourceLocation(${jstr(env.modId)}, "jei_plugin");
    }

    @Override
    public void registerCategories(mezz.jei.api.registration.IRecipeCategoryRegistration registration) {
        mezz.jei.api.helpers.IGuiHelper guiHelper = registration.getJeiHelpers().getGuiHelper();
${all.map((m) => `        registration.addRecipeCategories(new ${pascal(m.id)}Category(guiHelper));`).join("\n")}
    }

    @Override
    public void registerRecipes(mezz.jei.api.registration.IRecipeRegistration registration) {
${all.map((m) => `        registration.addRecipes(java.util.Arrays.asList(${recipesOf(m).join(", ")}), ${uid(m)});`).join("\n")}
    }

    @Override
    public void registerRecipeCatalysts(mezz.jei.api.registration.IRecipeCatalystRegistration registration) {
${all.flatMap((m) => [m.icon, ...m.catalysts].map((item) => `        registration.addRecipeCatalyst(new ${Stack}(${itemExpr(env, item)}), ${uid(m)});`)).join("\n")}
    }
${categories}
}
`,
    });
    return { sources, entrypoints: [] };
  }

  if (env.loader !== "fabric") {
    // JEI 21 (1.21.5) / 31 (26.3): IRecipeType, a layout builder for the slots, crafting stations (no API marked for removal).
    const v26 = env.mc === "26.3";
    const G = v26 ? "net.minecraft.client.gui.GuiGraphicsExtractor" : "net.minecraft.client.gui.GuiGraphics";
    const text = (t: string, x: number, y: number) => v26
      ? `graphics.text(net.minecraft.client.Minecraft.getInstance().font, ${t}, ${x}, ${y}, 0xFF404040, false);`
      : `graphics.drawString(net.minecraft.client.Minecraft.getInstance().font, ${t}, ${x}, ${y}, 0xFF404040, false);`;
    const RL = v26 ? "net.minecraft.resources.Identifier" : "net.minecraft.resources.ResourceLocation";
    const type = (m: Machine) => `${pascal(m.id).toUpperCase()}_TYPE`;
    const categories = all.map((m) => `
    public static class ${pascal(m.id)}Category implements mezz.jei.api.recipe.category.IRecipeCategory<${recipeClass}> {
        private final mezz.jei.api.gui.drawable.IDrawable icon;

        public ${pascal(m.id)}Category(mezz.jei.api.helpers.IGuiHelper guiHelper) {
            this.icon = guiHelper.createDrawableItemStack(new ${Stack}(${itemExpr(env, m.icon)}));
        }

        @Override public mezz.jei.api.recipe.types.IRecipeType<${recipeClass}> getRecipeType() { return ${type(m)}; }
        @Override public net.minecraft.network.chat.Component getTitle() { return net.minecraft.network.chat.Component.literal(${jstr(m.title)}); }
        @Override public mezz.jei.api.gui.drawable.IDrawable getIcon() { return this.icon; }
        @Override public int getWidth() { return ${width(m)}; }
        @Override public int getHeight() { return ${height(m)}; }

        @Override
        public void setRecipe(mezz.jei.api.gui.builder.IRecipeLayoutBuilder builder, ${recipeClass} recipe, mezz.jei.api.recipe.IFocusGroup focuses) {
            for (int i = 0; i < recipe.inputs.size(); i++) builder.addSlot(mezz.jei.api.recipe.RecipeIngredientRole.INPUT, i * ${SLOT} + 1, 1).add(recipe.inputs.get(i));
            for (int i = 0; i < recipe.outputs.size(); i++) builder.addSlot(mezz.jei.api.recipe.RecipeIngredientRole.OUTPUT, ${outX(m)} + i * ${SLOT} + 1, 1).add(recipe.outputs.get(i));
        }

        @Override
        public void draw(${recipeClass} recipe, mezz.jei.api.gui.ingredient.IRecipeSlotsView slots, ${G} graphics, double mouseX, double mouseY) {
            ${text('"->"', m.inputs * SLOT + 8, 5)}
            if (!recipe.info().isEmpty()) ${text("recipe.info()", 0, SLOT + 2)}
        }
    }`).join("\n");
    sources.push({
      path: `${dir}/${cls}.java`,
      code: `package ${pkg};

/** Generated by MCEdge: JEI plugin with a recipe category per machine block. */
@mezz.jei.api.JeiPlugin
public class ${cls} implements mezz.jei.api.IModPlugin {
${all.map((m) => `    public static final mezz.jei.api.recipe.types.IRecipeType<${recipeClass}> ${type(m)} = mezz.jei.api.recipe.types.IRecipeType.create(${jstr(env.modId)}, ${jstr(m.id)}, ${recipeClass}.class);`).join("\n")}

    @Override
    public ${RL} getPluginUid() {
        return ${RL}.fromNamespaceAndPath(${jstr(env.modId)}, "jei_plugin");
    }

    @Override
    public void registerCategories(mezz.jei.api.registration.IRecipeCategoryRegistration registration) {
        mezz.jei.api.helpers.IGuiHelper guiHelper = registration.getJeiHelpers().getGuiHelper();
${all.map((m) => `        registration.addRecipeCategories(new ${pascal(m.id)}Category(guiHelper));`).join("\n")}
    }

    @Override
    public void registerRecipes(mezz.jei.api.registration.IRecipeRegistration registration) {
${all.map((m) => `        registration.addRecipes(${type(m)}, java.util.Arrays.asList(${recipesOf(m).join(", ")}));`).join("\n")}
    }

    @Override
    public void registerRecipeCatalysts(mezz.jei.api.registration.IRecipeCatalystRegistration registration) {
${all.flatMap((m) => [m.icon, ...m.catalysts].map((item) => `        registration.addCraftingStation(${type(m)}, new ${Stack}(${itemExpr(env, item)}));`)).join("\n")}
    }
${categories}
}
`,
    });
    return { sources, entrypoints: [] };
  }

  // REI (Fabric 1.21.5 / 26.3): a display per recipe, a category drawn from REI's widgets.
  const display = (m: Machine) => `${pascal(m.id)}Display`;
  const id = (m: Machine) => `${pascal(m.id).toUpperCase()}_ID`;
  const recipes = (m: Machine) => `${pascal(m.id).toUpperCase()}_RECIPES`;
  const blocks = all.map((m) => `
    public static class ${display(m)} extends me.shedaniel.rei.api.common.display.basic.BasicDisplay {
        /** A display is saved and synced as the index of its recipe in ${recipes(m)}. */
        public static final me.shedaniel.rei.api.common.display.DisplaySerializer<${display(m)}> SERIALIZER = me.shedaniel.rei.api.common.display.DisplaySerializer.of(
            com.mojang.serialization.Codec.INT.fieldOf("recipe").xmap(${display(m)}::new, d -> d.index),
            net.minecraft.network.codec.ByteBufCodecs.VAR_INT.map(${display(m)}::new, d -> d.index).cast(), false);
        public final int index;
        public final ${recipeClass} recipe;

        public ${display(m)}(int index) {
            super(ingredients(${recipes(m)}.get(index).inputs), ingredients(${recipes(m)}.get(index).outputs));
            this.index = index;
            this.recipe = ${recipes(m)}.get(index);
        }

        @Override
        public me.shedaniel.rei.api.common.category.CategoryIdentifier<?> getCategoryIdentifier() {
            return ${id(m)};
        }

        @Override
        public me.shedaniel.rei.api.common.display.DisplaySerializer<? extends me.shedaniel.rei.api.common.display.Display> getSerializer() {
            return SERIALIZER;
        }
    }

    public static class ${pascal(m.id)}Category implements me.shedaniel.rei.api.client.registry.display.DisplayCategory<${display(m)}> {
        @Override public me.shedaniel.rei.api.common.category.CategoryIdentifier<? extends ${display(m)}> getCategoryIdentifier() { return ${id(m)}; }
        @Override public net.minecraft.network.chat.Component getTitle() { return net.minecraft.network.chat.Component.literal(${jstr(m.title)}); }
        @Override public me.shedaniel.rei.api.client.gui.Renderer getIcon() { return me.shedaniel.rei.api.common.util.EntryStacks.of(${itemExpr(env, m.icon)}); }
        @Override public int getDisplayHeight() { return ${height(m) + 16}; }
        @Override public int getDisplayWidth(${display(m)} display) { return ${width(m) + 16}; }

        @Override
        public java.util.List<me.shedaniel.rei.api.client.gui.widgets.Widget> setupDisplay(${display(m)} display, me.shedaniel.math.Rectangle bounds) {
            java.util.List<me.shedaniel.rei.api.client.gui.widgets.Widget> widgets = new java.util.ArrayList<>();
            widgets.add(me.shedaniel.rei.api.client.gui.widgets.Widgets.createRecipeBase(bounds));
            int x = bounds.x + 8, y = bounds.y + 8;
            for (int i = 0; i < display.getInputEntries().size(); i++)
                widgets.add(me.shedaniel.rei.api.client.gui.widgets.Widgets.createSlot(new me.shedaniel.math.Point(x + i * ${SLOT}, y)).entries(display.getInputEntries().get(i)).markInput());
            widgets.add(me.shedaniel.rei.api.client.gui.widgets.Widgets.createArrow(new me.shedaniel.math.Point(x + ${m.inputs * SLOT + 2}, y)));
            for (int i = 0; i < display.getOutputEntries().size(); i++)
                widgets.add(me.shedaniel.rei.api.client.gui.widgets.Widgets.createSlot(new me.shedaniel.math.Point(x + ${outX(m)} + i * ${SLOT}, y)).entries(display.getOutputEntries().get(i)).markOutput());
            if (!display.recipe.info().isEmpty())
                widgets.add(me.shedaniel.rei.api.client.gui.widgets.Widgets.createLabel(new me.shedaniel.math.Point(x, y + ${SLOT + 2}), net.minecraft.network.chat.Component.literal(display.recipe.info())).leftAligned().noShadow().color(0xFF404040));
            return widgets;
        }
    }`).join("\n");
  sources.push({
    path: `${dir}/${cls}.java`,
    code: `package ${pkg};

/** Generated by MCEdge: REI client plugin with a category per machine block (entrypoint rei_client). */
public class ${cls} implements me.shedaniel.rei.api.client.plugins.REIClientPlugin {
${all.map((m) => `    public static final me.shedaniel.rei.api.common.category.CategoryIdentifier<${display(m)}> ${id(m)} = me.shedaniel.rei.api.common.category.CategoryIdentifier.of(${jstr(env.modId)}, ${jstr(m.id)});\n    static final java.util.List<${recipeClass}> ${recipes(m)} = java.util.Arrays.asList(${recipesOf(m).join(", ")});`).join("\n")}

    static java.util.List<me.shedaniel.rei.api.common.entry.EntryIngredient> ingredients(java.util.List<${Stack}> stacks) {
        java.util.List<me.shedaniel.rei.api.common.entry.EntryIngredient> list = new java.util.ArrayList<>();
        for (${Stack} stack : stacks) list.add(me.shedaniel.rei.api.common.util.EntryIngredients.of(stack));
        return list;
    }

    @Override
    public void registerCategories(me.shedaniel.rei.api.client.registry.category.CategoryRegistry registry) {
${all.map((m) => `        registry.add(new ${pascal(m.id)}Category());\n${[m.icon, ...m.catalysts].map((item) => `        registry.addWorkstations(${id(m)}, me.shedaniel.rei.api.common.util.EntryStacks.of(${itemExpr(env, item)}));`).join("\n")}`).join("\n")}
    }

    @Override
    public void registerDisplays(me.shedaniel.rei.api.client.registry.display.DisplayRegistry registry) {
${all.map((m) => `        for (int i = 0; i < ${recipes(m)}.size(); i++) registry.add(new ${display(m)}(i));`).join("\n")}
    }
${blocks}
}
`,
  });
  return { sources, entrypoints: [{ name: "rei_client", classes: JSON.stringify([`${pkg}.${cls}`]) }] };
}
