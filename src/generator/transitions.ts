import { SLIDE_DISTANCE } from "../elements/transitions.ts";
import type { ProcEnv } from "../procedures/compile.ts";
import type { JavaSource } from "../procedures/runtime.ts";

/**
 * <Mod>Transitions (Q228, Q229): the one runtime helper for show / hide timing and animated image frames, generated once
 * per mod when the mod has bubbles or radial menus, the same code on every engine (no engine types in it). The rules
 * repeat src/elements/transitions.ts (`transitionState`, `ease`) and src/resources/textureAnimation.ts (`frameAt` with
 * playback modes applied), which the editor previews run, so the game and the editor move the same way.
 *
 * Timing: reads {"appear": {"effects": [...], "ticks": n, "easing": "..."}, "disappear": {...}, "active": n} and gives
 * {alpha, scale, offset} for an age in ticks, appearing or leaving. Frames: the frame list an image plays (its own
 * order and times from the .png.mcmeta, a mode's backwards pass or held frame already applied) and the frame shown after
 * some ticks.
 */
export function transitionsSource(env: ProcEnv): JavaSource {
  const cls = `${env.modClass}Transitions`;
  return {
    path: `${env.pkg.replaceAll(".", "/")}/procedures/${cls}.java`,
    code: `package ${env.pkg}.procedures;

/** Generated by MCEdge: show / hide transitions and animated image frames (Q228, Q229), driven by data files. */
public final class ${cls} {
    private ${cls}() {}

    public static final int FADE = 1, SCALE = 2, SLIDE_UP = 4, SLIDE_DOWN = 8;
    /** How far a slide moves, as a fraction of the element's height or size. */
    public static final float SLIDE = ${SLIDE_DISTANCE}F;

    private static float clamp(float x) {
        return Math.min(1.0F, Math.max(0.0F, x));
    }

    /** Easing curve: 0 linear, 1 ease out, 2 ease in-out, 3 back (overshoots 1 on the way, settles at 1). */
    public static float ease(int easing, float x) {
        float t = clamp(x);
        switch (easing) {
            case 1: {
                float u = 1.0F - t;
                return 1.0F - u * u * u;
            }
            case 2: {
                float u = -2.0F * t + 2.0F;
                return t < 0.5F ? 4.0F * t * t * t : 1.0F - u * u * u / 2.0F;
            }
            case 3: {
                float u = t - 1.0F;
                return 1.0F + 2.70158F * u * u * u + 1.70158F * u * u;
            }
            default:
                return t;
        }
    }

    /** One transition: a set of effects, a length in ticks and an easing. */
    public static final class Transition {
        public final int effects, ticks, easing;

        Transition(com.google.gson.JsonObject o) {
            int mask = 0;
            int curve = 0;
            int length = 5;
            if (o != null) {
                if (o.has("effects")) {
                    for (com.google.gson.JsonElement e : o.getAsJsonArray("effects")) {
                        String name = e.getAsString();
                        if ("fade".equals(name)) mask |= FADE;
                        else if ("scale".equals(name)) mask |= SCALE;
                        else if ("slide_up".equals(name)) mask |= SLIDE_UP;
                        else if ("slide_down".equals(name)) mask |= SLIDE_DOWN;
                    }
                }
                if (o.has("ticks")) length = o.get("ticks").getAsInt();
                String name = o.has("easing") ? o.get("easing").getAsString() : "linear";
                curve = "ease_out".equals(name) ? 1 : "ease_in_out".equals(name) ? 2 : "back".equals(name) ? 3 : 0;
            }
            effects = mask;
            ticks = Math.max(1, length);
            easing = curve;
        }

        /** Ticks it takes: none without effects. */
        public int length() {
            return effects == 0 ? 0 : ticks;
        }

        /**
         * {alpha 0..1, scale, offset} \`age\` ticks in. Appearing runs from hidden to shown, leaving the same curve backwards;
         * the offset is a fraction of the height, up positive (slide up rises into place, and rises away when leaving).
         */
        public float[] state(float age, boolean leaving) {
            float length = length();
            float p = length == 0.0F ? 1.0F : clamp(age / length);
            float s = ease(easing, leaving ? 1.0F - p : p);
            float away = (1.0F - s) * SLIDE;
            float slide = ((effects & SLIDE_UP) != 0 ? -away : 0.0F) + ((effects & SLIDE_DOWN) != 0 ? away : 0.0F);
            return new float[] { (effects & FADE) != 0 ? clamp(s) : 1.0F, (effects & SCALE) != 0 ? Math.max(0.0F, s) : 1.0F, leaving ? -slide : slide };
        }
    }

    /** How an element shows and hides: the data's "timing" object (null reads as the defaults). */
    public static final class Timing {
        public final Transition appear, disappear;
        /** Ticks from showing until it starts to go (0: until cleared). */
        public final int active;

        public Timing(com.google.gson.JsonObject o) {
            appear = new Transition(o != null && o.has("appear") ? o.getAsJsonObject("appear") : null);
            disappear = new Transition(o != null && o.has("disappear") ? o.getAsJsonObject("disappear") : null);
            active = o != null && o.has("active") ? Math.max(0, o.get("active").getAsInt()) : 0;
        }

        /** {alpha, scale, offset} \`age\` ticks after it appeared. */
        public float[] appearing(float age) {
            return appear.state(age, false);
        }

        /** {alpha, scale, offset} \`age\` ticks after it started to go. */
        public float[] leaving(float age) {
            return disappear.state(age, true);
        }
    }

    /** The frames an animated image plays: an order with a time for each, one pass of a once mode, then a held frame. */
    public static final class Frames {
        /** Frames in the image (a strip of square frames). */
        public final int count;
        private final int[] index, time;
        private final int total, hold;

        private Frames(int count, int[] index, int[] time, int hold) {
            this.count = Math.max(1, count);
            this.index = index;
            this.time = time;
            int sum = 0;
            for (int t : time) sum += t;
            this.total = Math.max(1, sum);
            this.hold = hold;
        }

        /** Every frame in order, \`time\` ticks each, looping. */
        public static Frames still(int count, int time) {
            int n = Math.max(1, count);
            int[] index = new int[n], times = new int[n];
            for (int i = 0; i < n; i++) {
                index[i] = i;
                times[i] = Math.max(1, time);
            }
            return new Frames(n, index, times, -1);
        }

        /** Reads <prefix>Frames, <prefix>Time, <prefix>Seq ([[frame, ticks], ...]) and <prefix>Hold (-1: loops) of a data object. */
        public static Frames of(com.google.gson.JsonObject o, String prefix) {
            int count = o.has(prefix + "Frames") ? o.get(prefix + "Frames").getAsInt() : 1;
            int base = o.has(prefix + "Time") ? o.get(prefix + "Time").getAsInt() : 1;
            if (!o.has(prefix + "Seq")) return still(count, base);
            com.google.gson.JsonArray seq = o.getAsJsonArray(prefix + "Seq");
            if (seq.size() == 0) return still(count, base);
            int[] index = new int[seq.size()], times = new int[seq.size()];
            for (int i = 0; i < seq.size(); i++) {
                com.google.gson.JsonArray entry = seq.get(i).getAsJsonArray();
                index[i] = Math.max(0, Math.min(Math.max(1, count) - 1, entry.get(0).getAsInt()));
                times[i] = Math.max(1, entry.get(1).getAsInt());
            }
            return new Frames(count, index, times, o.has(prefix + "Hold") ? o.get(prefix + "Hold").getAsInt() : -1);
        }

        /** Whether it plays from when the element appeared (a once mode), not from the game clock. */
        public boolean once() {
            return hold >= 0;
        }

        /** The frame shown \`ticks\` after it started. */
        public int at(long ticks) {
            if (count <= 1) return 0;
            if (hold >= 0 && ticks >= total) return hold;
            long t = ((ticks % total) + total) % total;
            for (int i = 0; i < index.length; i++) {
                if (t < time[i]) return index[i];
                t -= time[i];
            }
            return index[index.length - 1];
        }

        /** {first v, last v} of the frame shown \`ticks\` after it started, over a strip of the frames. */
        public float[] v(long ticks) {
            int frame = at(ticks);
            return new float[] { (float) frame / count, (float) (frame + 1) / count };
        }
    }
}
`,
  };
}
