/**
 * Seatable blocks (Q225), one data-driven runtime for every engine.
 *
 * Data: every block element with the Seat page on becomes one entry of data/<modid>/seats.json (src/elements/seats.ts):
 * its seats in blocks for the block facing north, the empty hand rule and the dismount rule. No block gets code of its own.
 *
 * Runtime: <Mod>Seats reads seats.json from the mod jar and listens to right clicks on blocks: on a seat block it sits
 * the player on the free seat nearest the click (free: no rider on it and, with a lying rider on either, none close
 * enough to share its room), turned with the block's facing property; an invisible, never saved
 * <Mod>Seats.Seat entity at the seat surface carries the player and goes away when they stand up (sneak, procedure) or
 * the block is broken or replaced. A lying seat lays its rider on the back along the seat's yaw (a pose only: no bed,
 * no sleep). A click on any part of a block spanning several cells (Q226) seats on the whole block. Procedures sit an
 * entity on any block, read whether it sits and stand it up.
 */

/** Where the mod's seats.json sits under src/main/resources. */
export const seatDataPath = (modId: string) => `data/${modId}/seats.json`;
/** Registry path of the seat entity; long enough not to clash with an entity element. */
export const SEAT_ENTITY = "mcedge_seat";
const TYPES = "SeatEntities";

const seatsClass = (env: GenEnv) => `${env.project.mod.package}.seat.${modClassName(env)}Seats`;

/** Whether procedures call <Mod>Seats (the seat blocks). */
const procedureUsesSeats = (env: GenEnv) =>
  [...procedureBuild(env).compiled.values()].some((c) => `${c.source}${c.clientSource ?? ""}`.includes(`${modClassName(env)}Seats.`));

/** Seat outputs of a project: seats.json, the runtime and its registration; nothing without seat blocks or seat procedures. */
export function seatOutputs(env: GenEnv): { files: ResourceFile[]; sources: JavaSourceFile[]; init: string[]; clientInit: string[]; mixins: Mixin[] } {
  const blocks = (env.generated.block ?? []).filter((b) => b.seatable === true);
  if (!blocks.length && !procedureUsesSeats(env)) return { files: [], sources: [], init: [], clientInit: [], mixins: [] };
  const data = Object.fromEntries(blocks.map((b) => [`${env.modId}:${b.id}`, seatEntry(b, spannedCells(b))]));
  const types = entityTypeClass(env, TYPES, [{
    constant: "SEAT", id: SEAT_ENTITY, entityClass: `${seatsClass(env)}.Seat`, category: "MISC",
    width: 0.001, height: 0.001, trackingRange: 10, updateInterval: 20,
    // 1.21.5+ refuses riding an entity type that cannot be saved; there the seat says it is not saved instead.
    noSave: env.mc === "1.16.5",
  }]);
  const type = entityTypeValue(env, TYPES, "SEAT");
  const factory = env.mc === "1.16.5"
    ? `manager -> new net.minecraft.client.renderer.entity.EntityRenderer<${seatsClass(env)}.Seat>(manager) {
                @Override
                public net.minecraft.util.ResourceLocation getTextureLocation(${seatsClass(env)}.Seat seat) {
                    return net.minecraft.client.renderer.texture.AtlasTexture.LOCATION_BLOCKS;
                }
            }`
    : "net.minecraft.client.renderer.entity.NoopRenderer::new";
  return {
    files: [{ path: seatDataPath(env.modId), json: JSON.stringify(data, null, 2) }],
    sources: [types.source, seatsSource(env, type)],
    init: [types.init, useListener(env)],
    clientInit: [rendererRegistration(env, [{ type, factory }])],
    mixins: env.loader === "fabric" ? [lyingLegsMixin(env)] : [],
  };
}

interface Mixin { id: string; code: string; client: boolean }

/**
 * Fabric: a lying rider's legs stay straight. Vanilla draws every rider with its legs bent forward; Forge and NeoForge
 * ask the vehicle (shouldRiderSit), Fabric has no such hook, so a mixin clears the passenger flag after the render state is filled.
 */
function lyingLegsMixin(env: GenEnv): Mixin {
  const at = "org.spongepowered.asm.mixin.injection";
  const id = "SeatLyingMixin";
  return {
    id,
    client: true,
    code: `package ${env.project.mod.package}.mixin;

/** Generated by MCEdge: a player lying on a seat (Q225) is drawn with straight legs. */
@org.spongepowered.asm.mixin.Mixin(net.minecraft.client.renderer.entity.HumanoidMobRenderer.class)
public abstract class ${id} {
    @${at}.Inject(method = "extractHumanoidRenderState", at = @${at}.At("TAIL"))
    private static void ${env.modId}$lying(net.minecraft.world.entity.LivingEntity entity, net.minecraft.client.renderer.entity.state.HumanoidRenderState state, float partialTick, net.minecraft.client.renderer.item.ItemModelResolver items, ${at}.callback.CallbackInfo info) {
        if (${seatsClass(env)}.isLying(entity)) state.isPassenger = false;
    }
}
`,
  };
}

/** The right-click listener (both sides): the client swings the arm, the server sits the player. */
function useListener(env: GenEnv): string {
  const use = `${seatsClass(env)}.use`;
  if (env.loader === "forge") {
    return `net.minecraftforge.common.MinecraftForge.EVENT_BUS.addListener(net.minecraftforge.eventbus.api.EventPriority.HIGH, false, net.minecraftforge.event.entity.player.PlayerInteractEvent.RightClickBlock.class, event -> {
            if (${use}(event.getPlayer(), event.getWorld(), event.getPos(), event.getHitVec().getLocation(), event.getHand() == net.minecraft.util.Hand.MAIN_HAND)) {
                event.setCanceled(true);
                event.setCancellationResult(net.minecraft.util.ActionResultType.SUCCESS);
            }
        });`;
  }
  if (env.loader === "neoforge") {
    return `net.neoforged.neoforge.common.NeoForge.EVENT_BUS.addListener(net.neoforged.bus.api.EventPriority.HIGH, false, net.neoforged.neoforge.event.entity.player.PlayerInteractEvent.RightClickBlock.class, event -> {
            if (${use}(event.getEntity(), event.getLevel(), event.getPos(), event.getHitVec().getLocation(), event.getHand() == net.minecraft.world.InteractionHand.MAIN_HAND)) {
                event.setCanceled(true);
                event.setCancellationResult(net.minecraft.world.InteractionResult.SUCCESS);
            }
        });`;
  }
  return `net.fabricmc.fabric.api.event.player.UseBlockCallback.EVENT.register((player, world, hand, hit) ->
            ${use}(player, world, hit.getBlockPos(), hit.getLocation(), hand == net.minecraft.world.InteractionHand.MAIN_HAND) ? net.minecraft.world.InteractionResult.SUCCESS : net.minecraft.world.InteractionResult.PASS);`;
}

