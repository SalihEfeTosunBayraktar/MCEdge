import { idExpr, jstr, pascal } from "./java.ts";
import type { GenEnv, JavaSourceFile } from "./typeModule.ts";

/**
 * Code-registered objects (enchantments on 1.16.5, mob effects, potions, particle types, attributes, ...): one
 * generated class per registry holding a field per element, registered through the loader's own mechanism.
 * Forge 1.16.5 and NeoForge use a DeferredRegister on the mod bus; Fabric registers when the class loads.
 */
export interface RegistryEntry {
  /** Field name, "RUBY". */
  constant: string;
  /** Registry path, "ruby". */
  id: string;
  /** Java expression creating the object. */
  factory: string;
}

export interface RegistrySpec {
  /** Class name suffix: "Effects" -> <Mod>Effects. */
  name: string;
  /** Fully qualified value type. */
  valueType: string;
  /** Element type of the registry when it differs from the value type (ParticleType<?> for particle types). */
  registryType?: string;
  /** 1.16.5 Forge registry expression (net.minecraftforge.registries.ForgeRegistries.ENCHANTMENTS). */
  forge?: string;
  /** Registries / BuiltInRegistries constant name on 1.21.5+ (MOB_EFFECT). */
  key?: string;
  entries: RegistryEntry[];
  /** Extra class members (static helpers). */
  members?: string;
}

export interface RegistryClass {
  source: JavaSourceFile;
  /** Constructor (Forge/NeoForge, `modBus` in scope) or onInitialize (Fabric) statement. */
  init: string;
  /** Fully qualified class name. */
  owner: string;
}

export const modClassName = (env: GenEnv) => `${pascal(env.modId)}Mod`;

export function registryClassName(env: GenEnv, name: string): string {
  return `${env.project.mod.package}.init.${modClassName(env)}${name}`;
}

/** Java expression of a registered element's value. */
export function registeredValue(env: GenEnv, name: string, constant: string): string {
  const owner = registryClassName(env, name);
  return env.loader === "fabric" ? `${owner}.${constant}.value()` : `${owner}.${constant}.get()`;
}

/** Java expression of a registered element's Holder (1.21.5+). */
export function registeredHolder(env: GenEnv, name: string, constant: string): string {
  return `${registryClassName(env, name)}.${constant}`;
}

export function registryClass(env: GenEnv, spec: RegistrySpec): RegistryClass {
  const pkg = env.project.mod.package;
  const cls = `${modClassName(env)}${spec.name}`;
  const owner = `${pkg}.init.${cls}`;
  const T = spec.valueType;
  const R = spec.registryType ?? T;
  let fields: string;
  let init: string;
  if (env.mc === "1.16.5") {
    fields = `    public static final net.minecraftforge.registries.DeferredRegister<${R}> REGISTRY = net.minecraftforge.registries.DeferredRegister.create(${spec.forge}, ${jstr(env.modId)});
${spec.entries.map((e) => `    public static final net.minecraftforge.fml.RegistryObject<${T}> ${e.constant} = REGISTRY.register(${jstr(e.id)}, () -> ${e.factory});`).join("\n")}`;
    init = `${owner}.REGISTRY.register(modBus);`;
  } else if (env.loader === "neoforge") {
    fields = `    public static final net.neoforged.neoforge.registries.DeferredRegister<${R}> REGISTRY = net.neoforged.neoforge.registries.DeferredRegister.create(net.minecraft.core.registries.Registries.${spec.key}, ${jstr(env.modId)});
${spec.entries.map((e) => `    public static final net.neoforged.neoforge.registries.DeferredHolder<${R}, ${T}> ${e.constant} = REGISTRY.register(${jstr(e.id)}, () -> ${e.factory});`).join("\n")}`;
    init = `${owner}.REGISTRY.register(modBus);`;
  } else {
    const key = (id: string) => `net.minecraft.resources.ResourceKey.create(net.minecraft.core.registries.Registries.${spec.key}, ${idExpr(env, `${env.modId}:${id}`)})`;
    fields = `${spec.entries.map((e) => `    public static final net.minecraft.core.Holder<${R}> ${e.constant} = net.minecraft.core.Registry.registerForHolder(net.minecraft.core.registries.BuiltInRegistries.${spec.key}, ${key(e.id)}, ${e.factory});`).join("\n")}

    /** Loads the class, which registers its entries. */
    public static void init() {}`;
    init = `${owner}.init();`;
  }
  const code = `package ${pkg}.init;

/** Generated by MCEdge. */
public final class ${cls} {
    private ${cls}() {}

${fields}
${spec.members ?? ""}}
`;
  return { source: { path: `${pkg.replaceAll(".", "/")}/init/${cls}.java`, code }, init, owner };
}
