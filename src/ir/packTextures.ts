/**
 * A 64 x 32 armor layer in the player model's layout: layer 1 covers head, body, arms and feet, layer 2 the legs and
 * waist. Each covered box is the colour with a darker rim.
 */
export function armorLayer(colour: string, layer: 1 | 2): PackImage {
  const width = 64, height = 32;
  const data = new Uint8Array(width * height * 4);
  const base = hexRgb(colour);
  const box = (x: number, y: number, w: number, h: number) => {
    for (let py = y; py < y + h; py++) for (let px = x; px < x + w; px++) {
      const rim = py === y || px === x || py === y + h - 1 || px === x + w - 1;
      const f = rim ? SHADES[1] : (px + py) % 5 === 0 ? SHADES[4] : SHADES[3];
      data.set([...base.map((v) => Math.max(0, Math.min(255, Math.round(v * f)))), 255], (py * width + px) * 4);
    }
  };
  if (layer === 1) {
    box(0, 0, 32, 16); // head
    box(16, 16, 24, 16); // body
    box(40, 16, 16, 16); // arms
    box(0, 16, 16, 16); // boots (legs box)
  } else {
    box(16, 16, 24, 16); // waist
    box(0, 16, 16, 16); // legs
  }
  return { width, height, data };
}
