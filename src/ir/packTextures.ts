/**
 * Textures the pack wizards draw (KUYRUK 134): small pixel-art masks tinted with the pack's colour, so a pack starts
 * with textures that read as what they are (an ingot, an ore, a pickaxe) and can be repainted in the texture editor.
 * Mask characters: "." transparent, "1"-"5" the pack colour from dark to light, "h"/"H" a wooden handle, "s"/"S"/"t"
 * stone, "k" a dark outline.
 */

export interface PackImage { width: number; height: number; data: Uint8Array }

type Rgb = [number, number, number];
const FIXED: Record<string, Rgb> = { h: [0x5a, 0x3d, 0x22], H: [0x89, 0x63, 0x3a], s: [0x6b, 0x6b, 0x6b], S: [0x84, 0x84, 0x84], t: [0x9a, 0x9a, 0x9a], k: [0x24, 0x22, 0x26] };
const SHADES = [0.42, 0.62, 0.82, 1, 1.22];

export function hexRgb(hex: string): Rgb {
  const m = /^#?([0-9a-f]{6})$/i.exec(hex.trim());
  if (!m) throw new Error(`not a colour: ${hex}`);
  const n = parseInt(m[1], 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

/** A mask (rows of equal length) painted with `colour`. */
export function paintMask(mask: string[], colour: string): PackImage {
  const base = hexRgb(colour);
  const height = mask.length, width = mask[0].length;
  const data = new Uint8Array(width * height * 4);
  mask.forEach((row, y) => {
    if (row.length !== width) throw new Error(`mask row ${y} is ${row.length} wide, not ${width}`);
    [...row].forEach((c, x) => {
      const rgb = c >= "1" && c <= "5" ? base.map((v) => Math.max(0, Math.min(255, Math.round(v * SHADES[Number(c) - 1])))) as Rgb : FIXED[c];
      if (!rgb) return;
      data.set([...rgb, 255], (y * width + x) * 4);
    });
  });
  return { width, height, data };
}

